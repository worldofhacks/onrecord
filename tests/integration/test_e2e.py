def _substation_ids(docs: list[Doc]) -> set[str]:
    return {doc.id for doc in docs if "substation" in doc.text.lower()}


def _write_jsonl_rows(path: Path, docs: list[Doc]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as fh:
        for doc in docs:
            fh.write(json.dumps(asdict(doc)) + "\n")


def _write_corpus_snapshot(path: Path, docs: list[Doc]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(path, "wt") as fh:
        for doc in docs:
            fh.write(json.dumps(asdict(doc)) + "\n")


def _run_cli(*args: str, timeout: int = CLI_TIMEOUT) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, "-m", "onrecord.cli", *args],
        capture_output=True,
        text=True,
        timeout=timeout,
    )


def _run_build_corpus(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, "-m", "onrecord.ingest.build_corpus", *args],
        capture_output=True,
        text=True,
        timeout=BUILD_TIMEOUT,
    )


