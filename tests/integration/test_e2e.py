# AC-2 — `--source county_meeting` filters to only county docs (metadata
# filter over retrieved hits). Index built directly (bypassing
# build_corpus) so this AC's failure surface is isolated to cli.py.
# --------------------------------------------------------------------------


def test_ac2_source_filter_returns_only_matching_source_type(tmp_path):
    # spec(T-010:AC-2)
    docs = _fixture_docs()
    index_dir = tmp_path / "index"
    InvertedIndex.build(docs).save(index_dir)

    substation_ids = _substation_ids(docs)
    county_substation_ids = {
        d.id for d in docs if d.id in substation_ids and d.source_type == "county_meeting"
    }
    other_substation_ids = substation_ids - county_substation_ids
    assert county_substation_ids, "fixture sanity: need >=1 county substation doc"
    assert other_substation_ids, "fixture sanity: need >=1 non-county substation doc"

    unfiltered = _run_cli("search", "substation", "--index", str(index_dir))
    assert unfiltered.returncode == 0
    for doc_id in substation_ids:
        assert f"id={doc_id}" in unfiltered.stdout

    filtered = _run_cli(
        "search", "substation", "--source", "county_meeting", "--index", str(index_dir)
    )
    assert filtered.returncode == 0, (
        f"cli search --source failed:\nstdout={filtered.stdout!r}\nstderr={filtered.stderr!r}"
    )
    for doc_id in county_substation_ids:
        assert f"id={doc_id}" in filtered.stdout
    for doc_id in other_substation_ids:
        assert f"id={doc_id}" not in filtered.stdout


