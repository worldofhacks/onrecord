# AC-1 — tokenize + normalize the ticket's canonical example
# --------------------------------------------------------------------------


def test_ac1_ticket_example_tokenizes_apostrophe_dash_and_alnum():
    # spec(T-002:AC-1)
    result = analyze("The Applicant's 240MW request—Loudoun County.")
    assert result == [
        "the",
        "applicant",
        "s",
        "240mw",
        "request",
        "loudoun",
        "county",
    ]


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        # letter+digit run with no separator stays one token (digits kept)
        ("Q3", ["q3"]),
        # hyphen is non-alphanumeric: splits digit run from letter
        ("10-K", ["10", "k"]),
        # no separator between digits and letter: stays fused
        ("10K", ["10k"]),
    ],
)
def test_ac1_alnum_runs_split_only_on_non_alphanumeric_separators(text, expected):
    # spec(T-002:AC-1)
    assert analyze(text) == expected


def test_ac1_preserves_order_and_duplicates():
    # spec(T-002:AC-1) -- position i must equal list index i; no dedup/sort
    assert analyze("The the THE") == ["the", "the", "the"]


def test_ac1_collapses_runs_of_separators_without_empty_tokens():
    # spec(T-002:AC-1)
    assert analyze("hello,,,   world!!") == ["hello", "world"]


def test_ac1_returns_list_of_str():
    # spec(T-002:AC-1)
    result = analyze("hello world")
    assert isinstance(result, list)
    assert all(isinstance(tok, str) for tok in result)


