@given(st.text(max_size=300))
@settings(deadline=None)
@example("")
@example("   ")
@example("The Applicant's 240MW request—Loudoun County.")
@example("Curaçao ＭＳＦＴ")
@example("北京市场")
@example("🔥🔥🔥")
def test_ac4_property_idempotent_after_rejoin(text):
    # spec(T-002:AC-4) -- re-analyzing analyzed-then-rejoined output is a no-op
    tokens = analyze(text)
    assert analyze(" ".join(tokens)) == tokens


@given(st.text(max_size=300))
@settings(deadline=None)
@example("")
@example("The Applicant's 240MW request—Loudoun County.")
@example("Curaçao ＭＳＦＴ")
@example("北京市场")
def test_ac4_property_output_tokens_match_lowercase_alnum_charset(text):
    # spec(T-002:AC-4) -- every token is `[a-z0-9]+` or non-Latin word chars:
    # non-empty, no internal whitespace, purely alphanumeric, never uppercase
    # (scripts without case, e.g. CJK, are vacuously "not uppercase").
    tokens = analyze(text)
    for tok in tokens:
        assert tok != "", "analyze() must drop empty tokens"
        assert tok == tok.strip(), f"token {tok!r} has leading/trailing whitespace"
        assert tok.isalnum(), f"token {tok!r} contains non-alphanumeric characters"
        assert not any(ch.isupper() for ch in tok), f"token {tok!r} is not fully case-folded"


