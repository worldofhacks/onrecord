def _patch_pool_candidates(monkeypatch, judgments_mod, docs):
    def _fake_pool_candidates(query, corpus_path, k_per_source, seed):
        return list(docs)

    monkeypatch.setattr(judgments_mod, "pool_candidates", _fake_pool_candidates)


def _run_cli(
    monkeypatch,
    judgments_mod,
    stdin_lines,
    *,
    corpus_path,
    out_path,
    query_id=_CLI_QUERY_ID,
    extra_args=None,
):
    monkeypatch.setattr("sys.stdin", io.StringIO("\n".join(stdin_lines) + "\n"))
    return judgments_mod.main(
        [
            "--query",
            _CLI_QUERY,
            "--query-id",
            query_id,
            "--corpus",
            str(corpus_path),
            "--out",
            str(out_path),
            *(extra_args or []),
        ]
    )


def _read_rows(out_path: Path):
    if not out_path.exists():
        return []
    return [json.loads(line) for line in out_path.read_text().splitlines() if line.strip()]


