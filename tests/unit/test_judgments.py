def test_pool_candidates_shuffle_actually_shuffles(pooling_corpus_path):
    # spec(T-009:AC-1) -- adversarial: order must genuinely be shuffled, not
    # just source-concatenation that happens to look different due to
    # dedup/random-source membership.
    pooling_mod = _import_pooling_module()
    pooled = pooling_mod.pool_candidates(_QUERY, str(pooling_corpus_path), _K_SMALL, _SEED_A)
    concat_order = _reference_concat_order(_QUERY, _fixture_docs(), _K_SMALL, _SEED_A)

