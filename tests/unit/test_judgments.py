def _reference_concat_order(query: str, docs: list[Doc], k_per_source: int, seed: int) -> list[Doc]:
    """Pre-shuffle concatenation order per the pinned algorithm (module
    docstring): grep hits ++ bm25 top-k ++ 3 random-sampled docs, deduped
    keeping first occurrence. Used ONLY to prove pool_candidates actually
    shuffles rather than just returning source-concatenation order.
    """
    q = query.lower()
    grep_docs = [d for d in docs if q in d.text.lower()][:k_per_source]

    tokenized_corpus = [d.text.lower().split() for d in docs]
    bm25 = BM25Okapi(tokenized_corpus)
    scores = bm25.get_scores(query.lower().split())
    order = sorted(range(len(docs)), key=lambda i: (-scores[i], i))
    bm25_docs = [docs[i] for i in order[:k_per_source]]

    rng = random.Random(seed)
    random_docs = rng.sample(docs, min(3, len(docs)))

    seen: set[str] = set()
    combined: list[Doc] = []
    for d in grep_docs + bm25_docs + random_docs:
        if d.id not in seen:
            seen.add(d.id)
            combined.append(d)
    return combined


