def test_prices_happy_path_matches_significant_move_and_nearby_receipt(tmp_path, monkeypatch):
    # spec(T-015:AC-2)
    api_module = _api_module()
    missing_index_dir = tmp_path / "no_such_index"  # AC-2: prices is index-independent

    series = [
        {"date": "2024-01-02", "close": 100.0},
        {"date": "2024-01-03", "close": 108.0},  # +8.0% -- flags at the default 5.0% threshold
    ]
    cache_dir = tmp_path / "prices_cache"
    _seed_price_cache(cache_dir, "VST", series)

    receipt_doc = Doc(
        id="vst-filing-1",
        text="a filing discussing VST operations",
        source_type="filing",
        venue_type="coached",
        date="2024-01-01",  # 2 days before the 2024-01-03 move -- inside the default 7-day window
        deep_link="https://sec.gov/edgar/vst-filing-1",
        ticker="VST",
    )
    corpus_path = tmp_path / "corpus" / "v1" / "corpus.jsonl.gz"
    _write_gz_corpus(corpus_path, [receipt_doc])

    with _client(
        api_module,
        monkeypatch,
        index_dir=missing_index_dir,
        corpus_path=corpus_path,
        prices_cache_dir=cache_dir,
    ) as client:
        resp = client.get("/api/prices/VST")

    assert resp.status_code == 200
    body = resp.json()
    assert set(body.keys()) == {"ticker", "series", "significant_moves"}
    assert body["ticker"] == "VST"
    assert body["series"] == series

    moves = body["significant_moves"]
    assert len(moves) == 1, f"expected exactly the +8.0% day flagged, got {moves}"
    move = moves[0]
    assert set(move.keys()) == {"date", "return_pct", "nearby_receipts"}
    assert move["date"] == "2024-01-03"
    assert move["return_pct"] == pytest.approx(8.0, abs=1e-9)
    assert move["nearby_receipts"] == [
        {
            "id": "vst-filing-1",
            "date": "2024-01-01",
            "source_type": "filing",
            "deep_link": "https://sec.gov/edgar/vst-filing-1",
        }
    ]


