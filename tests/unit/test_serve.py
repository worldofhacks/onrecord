def _build_index(tmp_path: Path, docs: list[Doc], name: str = "index") -> Path:
    """Build a real InvertedIndex (real analyzer) and save it to a fresh
    tmp dir; return that dir. Mirrors tests/unit/test_api.py's helper."""
    index = InvertedIndex.build(docs)
    index_dir = tmp_path / name
    index.save(index_dir)
    return index_dir


def _write_gz_corpus(path: Path, docs: list[Doc]) -> None:
    """Write `docs` as a gzipped corpus-v1 snapshot at `path`, in the exact
    row schema `onrecord.ingest.build_corpus.load_corpus_snapshot` reads
    back (mirrors `build_corpus.build_corpus`'s own writer)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(path, "wt", encoding="utf-8") as fh:
        for doc in docs:
            fh.write(json.dumps(asdict(doc)) + "\n")


def _write_ui_dir(tmp_path: Path, name: str = "ui") -> tuple[Path, str, str]:
    """Write a stub `index.html` + `support.js` under a fresh tmp dir;
    return (ui_dir, index_content, support_js_content)."""
    ui_dir = tmp_path / name
    ui_dir.mkdir(parents=True, exist_ok=True)
    index_content = "<!doctype html><html><body>T-015 STUB INDEX MARKER</body></html>"
    support_js_content = "// T-015 STUB SUPPORT.JS MARKER\nconsole.log('onrecord stub');\n"
    (ui_dir / "index.html").write_text(index_content, encoding="utf-8")
    (ui_dir / "support.js").write_text(support_js_content, encoding="utf-8")
    return ui_dir, index_content, support_js_content


def _seed_price_cache(
    cache_dir: Path, ticker: str, series: list[dict], fetched_at: datetime | None = None
) -> None:
    """Seed `<cache_dir>/<ticker>.json` in the exact shape
    `onrecord.ingest.prices`'s own `_write_cache` writes, fresh enough
    (well within the 1-day freshness window) that `fetch_eod` returns it
    verbatim with zero network calls."""
    cache_dir.mkdir(parents=True, exist_ok=True)
    if fetched_at is None:
        fetched_at = datetime.now(UTC) - timedelta(hours=1)
    payload = {"ticker": ticker, "fetched_at": fetched_at.isoformat(), "series": series}
    (cache_dir / f"{ticker}.json").write_text(json.dumps(payload), encoding="utf-8")


