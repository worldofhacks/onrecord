def TRIVIAL_ANALYZER(text: str) -> list[str]:
    return text.lower().split()


def _make_doc(doc_id: str, text: str, n: int = 0) -> Doc:
    return Doc(
        id=doc_id,
        text=text,
        source_type="filing",
        venue_type="written",
        date="2024-01-01",
        deep_link=f"https://example.test/doc/{n}",
    )


