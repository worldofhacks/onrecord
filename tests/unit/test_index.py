def test_save_load_round_trip_preserves_df_postings_and_doc_store(tmp_path):
    # spec(T-003:AC-3)
    doc_3x = _make_doc("doc-three", "substation substation substation transformer", 0)
    doc_1x = _make_doc("doc-one", "the substation is near the county line", 1)
    doc_0x = _make_doc("doc-zero", "no relevant term here at all", 2)
    docs = [doc_3x, doc_1x, doc_0x]

    idx = InvertedIndex.build(docs, analyzer=TRIVIAL_ANALYZER)

    save_path = tmp_path / "index-round-trip"
    idx.save(save_path)
    loaded = InvertedIndex.load(save_path)

    assert loaded.doc_count() == idx.doc_count()

    all_terms = {tok for d in docs for tok in TRIVIAL_ANALYZER(d.text)}
    for term in all_terms:
        assert loaded.df(term) == idx.df(term), f"df mismatch after round-trip for {term!r}"

        before = idx.postings(term)
        after = loaded.postings(term)
        assert list(after.doc_ids) == list(before.doc_ids), f"doc_ids mismatch for {term!r}"
        assert list(after.tfs) == list(before.tfs), f"tfs mismatch for {term!r}"
        assert len(after.positions) == len(before.positions), f"positions len mismatch for {term!r}"
        for pos_before, pos_after in zip(before.positions, after.positions, strict=True):
            assert list(pos_after) == list(pos_before), f"positions mismatch for {term!r}"

    for doc in docs:
        assert loaded.get_doc(doc.id) == idx.get_doc(doc.id) == doc


def test_save_load_round_trip_survives_a_delete():
    # spec(T-003:AC-3)
    import tempfile
    from pathlib import Path

    doc_a = _make_doc("a", "substation transformer", 0)
    doc_b = _make_doc("b", "substation county", 1)
    idx = InvertedIndex.build([doc_a, doc_b], analyzer=TRIVIAL_ANALYZER)
    idx.delete("a")

    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "idx"
        idx.save(path)
        loaded = InvertedIndex.load(path)

    assert loaded.doc_count() == 1
    assert loaded.df("substation") == 1
    assert loaded.df("transformer") == 0
    try:
        loaded.get_doc("a")
    except KeyError:
        pass
    else:
        raise AssertionError("get_doc('a') should raise KeyError after a deleted doc round-trips")


