# AC-1 — df + postings tfs, correct sorted doc ids
# ---------------------------------------------------------------------------


def test_df_and_postings_tfs_with_correct_sorted_doc_ids():
    # spec(T-003:AC-1)
    doc_3x = _make_doc("doc-three", "substation substation substation transformer", 0)
    doc_1x = _make_doc("doc-one", "the substation is near the county line", 1)
    doc_0x = _make_doc("doc-zero", "no relevant term here at all", 2)

    idx = InvertedIndex.build([doc_3x, doc_1x, doc_0x], analyzer=TRIVIAL_ANALYZER)

    assert idx.df("substation") == 2

    postings = idx.postings("substation")
    doc_ids = list(postings.doc_ids)
    tfs = list(postings.tfs)

    assert len(doc_ids) == 2
    assert len(tfs) == 2
    # doc_ids must be sorted ascending with no duplicates.
    assert doc_ids == sorted(doc_ids)
    assert len(set(doc_ids)) == len(doc_ids)
    # doc_3x was built first -> smallest internal id -> sorts first, and its
    # tf (3) must precede doc_1x's tf (1), matching AC-1's [3, 1] literally.
    assert tfs == [3, 1]


