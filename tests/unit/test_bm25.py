@st.composite
def _idf_ordering_params(draw):
    """Fixed tf and doc_len == avg_doc_len (ratio 1) so the saturation
    factor is identical for both calls -- isolates the property to the IDF
    term specifically, per the ticket's own wording ("IDF strictly
    decreases")."""
    N = draw(st.integers(min_value=2, max_value=200))
    df1 = draw(st.integers(min_value=0, max_value=N - 1))
    df2 = draw(st.integers(min_value=df1 + 1, max_value=N))
    tf = draw(st.integers(min_value=1, max_value=50))
    doc_len = draw(st.floats(min_value=1.0, max_value=500.0, allow_nan=False, allow_infinity=False))
    return N, df1, df2, tf, doc_len


@given(params=_idf_ordering_params())
@settings(max_examples=100, deadline=None)
def test_property_idf_strictly_decreases_as_df_rises(params):
    # spec(T-011:AC-1) -- property: for fixed N, increasing df strictly
    # decreases the score (tf/doc_len/avg_doc_len held fixed and equal-ratio
    # so only the IDF term varies between the two calls).
    bm25_mod = _import_bm25_module()
    N, df1, df2, tf, doc_len = params
    assert df1 < df2

    score_low_df = bm25_mod.bm25_score(tf, df1, N, doc_len, doc_len)
    score_high_df = bm25_mod.bm25_score(tf, df2, N, doc_len, doc_len)

    assert score_low_df > score_high_df, (
        f"N={N} df1={df1} df2={df2}: lower df must score strictly higher"
    )


@st.composite
def _tf_monotonic_params(draw):
    N = draw(st.integers(min_value=1, max_value=200))
    df = draw(st.integers(min_value=0, max_value=N))
    tf = draw(st.integers(min_value=0, max_value=100))
    doc_len = draw(st.floats(min_value=1.0, max_value=500.0, allow_nan=False, allow_infinity=False))
    avg_doc_len = draw(
        st.floats(min_value=1.0, max_value=500.0, allow_nan=False, allow_infinity=False)
    )
    k1 = draw(st.floats(min_value=0.1, max_value=5.0, allow_nan=False, allow_infinity=False))
    b = draw(st.floats(min_value=0.0, max_value=1.0, allow_nan=False, allow_infinity=False))
    return N, df, tf, doc_len, avg_doc_len, k1, b


@given(params=_tf_monotonic_params())
@settings(max_examples=150, deadline=None)
def test_property_adding_a_query_term_occurrence_never_lowers_the_score(params):
    # spec(T-011:AC-2) -- property (ticket Test Plan): adding a query-term
    # occurrence (tf -> tf+1, everything else fixed) never lowers a doc's
    # score.
    bm25_mod = _import_bm25_module()
    N, df, tf, doc_len, avg_doc_len, k1, b = params

    lower_tf_score = bm25_mod.bm25_score(tf, df, N, doc_len, avg_doc_len, k1=k1, b=b)
    higher_tf_score = bm25_mod.bm25_score(tf + 1, df, N, doc_len, avg_doc_len, k1=k1, b=b)

    assert higher_tf_score >= lower_tf_score - 1e-9, (
        f"N={N} df={df} tf={tf}->{tf + 1} doc_len={doc_len} avg_doc_len={avg_doc_len} "
        f"k1={k1} b={b}: adding an occurrence must never lower the score "
        f"({higher_tf_score} < {lower_tf_score})"
    )
