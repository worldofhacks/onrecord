# --------------------------------------------------------------------------
# Reference formula -- computed with math.log at test time, never a
# hardcoded "expected score" decimal literal. Reused across many tests
# (mirrors the `_reference_concat_order` pattern in tests/unit/test_judgments.py).
# --------------------------------------------------------------------------


def _bm25_ref(
    tf: float, df: int, N: int, doc_len: float, avg_doc_len: float, k1: float = 1.5, b: float = 0.75
) -> float:
    idf = math.log(1 + (N - df + 0.5) / (df + 0.5))
    denom = tf + k1 * (1 - b + b * (doc_len / avg_doc_len))
    saturation = tf * (k1 + 1) / denom
    return idf * saturation


def _tf_in_doc(idx: InvertedIndex, term: str, internal_id: int) -> int:
    postings = idx.postings(term)
    doc_ids = list(postings.doc_ids)
    if internal_id not in doc_ids:
        return 0
    return list(postings.tfs)[doc_ids.index(internal_id)]


def _ref_doc_score(
    idx: InvertedIndex, internal_id: int, terms: list[str], k1: float = 1.5, b: float = 0.75
) -> float:
    """Hand-computed OR-semantics/sum-of-per-term-BM25 score for one doc,
    read entirely off the REAL InvertedIndex's own stats (df/N/doc_length/
    avg_doc_length) -- never off values this test file invented separately."""
    N = idx.doc_count()
    avg_len = idx.avg_doc_length()
    doc_len = idx.doc_length(internal_id)
    total = 0.0
    for term in terms:
        df = idx.df(term)
        tf = _tf_in_doc(idx, term, internal_id)
        total += _bm25_ref(tf, df, N, doc_len, avg_len, k1, b)
    return total


