def test_search_filter_then_truncate_holds_across_every_k_and_filter_combination(
    tmp_path, monkeypatch
):
    # spec(T-024:AC-2) -- the exhaustive invariant (design decision 5): for
    # every mode x filter x k, the served results are exactly the first `k`
    # of the mode's full ranking restricted to the matching docs. One
    # TestClient, 98 requests, no sampling.
    api_module = _api_module()
    provider = ScriptedProvider()
    filter_cases = [
        {},
        {"source": "filing"},
        {"source": "county_meeting"},
        {"venue": "sworn"},
        {"ticker": "VST"},
        {"jurisdiction": "Loudoun County, VA"},
        {"source": "county_meeting", "jurisdiction": "Fairfax County, VA"},
    ]

    def _matches(doc_id: str, params: dict) -> bool:
        source_type, venue_type, jurisdiction, ticker, _date = META[doc_id]
        actual = {
            "source": source_type,
            "venue": venue_type,
            "jurisdiction": jurisdiction,
            "ticker": ticker,
        }
        return all(actual[key] == value for key, value in params.items())

    with _client(
        api_module,
        monkeypatch,
        index_dir=_build_index(tmp_path),
        store_dir=_build_store(tmp_path, provider),
        provider=provider,
    ) as client:
        for mode in ("semantic", "hybrid"):
            for params in filter_cases:
                for k in (1, 2, 3, 4, 5, 6, 20):
                    resp = client.get(
                        "/api/search", params={"q": QUERY, "mode": mode, "k": k, **params}
                    )
                    assert resp.status_code == 200, (mode, params, k, resp.text)
                    expected = [doc_id for doc_id in MODE_ORDER[mode] if _matches(doc_id, params)][
                        :k
                    ]
                    assert _result_doc_ids(resp) == expected, (mode, params, k)


