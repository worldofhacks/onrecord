def test_fixture_question_ranks_exactly_like_the_query():
    # spec(T-024:AC-7) -- a second fixture self-check (not an API
    # assertion). `/api/search` is driven by QUERY while `/api/answer` is
    # driven by QUESTION, yet the answer tests above reuse LEXICAL_ORDER /
    # LEXICAL_SCORES. That transfer is legitimate only because QUESTION's
    # extra words ("what happened with") are BM25-INERT over this corpus:
    # they add no candidate docs and contribute tf=0 to every candidate, so
    # both the ranking and the scores are identical. Pinned here, with an
    # independent `ranked_search` recomputation, so an innocuous fixture-text
    # edit that breaks the transfer fails HERE rather than as a baffling
    # score mismatch three tests away.
    from onrecord.search.ranked import ranked_search

    index = InvertedIndex.build(_docs())
    by_query = ranked_search(index, QUERY, k=index.doc_count())
    by_question = ranked_search(index, QUESTION, k=index.doc_count())

    assert [hit.doc_id for hit in by_query] == LEXICAL_ORDER
    assert [hit.doc_id for hit in by_question] == LEXICAL_ORDER
    for hit in by_query:
        assert hit.score == pytest.approx(LEXICAL_SCORES[hit.doc_id], rel=1e-12)
    assert [hit.score for hit in by_question] == pytest.approx(
        [hit.score for hit in by_query], rel=1e-12
    )


