def _rrf_score(doc_id: str) -> float:
    """`sum over rankings containing id of 1/(k + rank)` — T-022's frozen
    formula, restated here so the hybrid expectations are independent of the
    implementation under test. An id absent from a ranking contributes
    nothing (no penalty term)."""
