def _save_store(directory: Path, pairs, provider: ScriptedProvider) -> Path:
    store = EmbeddingStore()
    store.embed_corpus([(chunk_id, text) for chunk_id, text in pairs], provider)
    store.save(directory)
    provider.calls.clear()  # only query-time calls are interesting afterwards
    return directory


def _build_store(tmp_path: Path, provider: ScriptedProvider, *, name: str = "embeddings") -> Path:
    """The complete, healthy store: one row per identity chunk."""
    return _save_store(
        tmp_path / name, [(chunk.chunk_id, chunk.text) for chunk in _fixture_chunks()], provider
    )


@contextlib.contextmanager
def _client(
    api_module,
    monkeypatch,
    *,
    index_dir: Path,
    store_dir: Path | None = None,
    provider=None,
    generator=None,
    min_confidence: str | None = None,
):
    """Open a TestClient over a fully isolated environment.

    Every env var in `_ISOLATED_ENV` is `delenv`'d first (delenv hygiene --
    a developer's exported OPENAI_API_KEY must never change a verdict here),
    then only what the test asks for is set. `ONRECORD_INDEX` /
    `ONRECORD_EMBED_STORE` are read at ASGI startup, so they are set BEFORE
    the context is entered (`test_api.py`'s AC-5 seam).

    `provider`/`generator` are installed on the module seams BEFORE startup
    too, so an implementation that resolves the provider's model at startup
    (to compute the default store location) sees the fake as well.

    `raise_server_exceptions=False` (design decision 4 in the module
    docstring): an unhandled exception becomes a real 500 response, exactly
    as deployed uvicorn behaves.
    """
    for name in _ISOLATED_ENV:
        monkeypatch.delenv(name, raising=False)
    monkeypatch.setenv("ONRECORD_INDEX", str(index_dir))
    if store_dir is not None:
        monkeypatch.setenv("ONRECORD_EMBED_STORE", str(store_dir))
    if min_confidence is not None:
        monkeypatch.setenv("ONRECORD_ANSWER_MIN_CONF", min_confidence)
    if provider is not None:
        monkeypatch.setattr(
            _seam(api_module, "embeddings"), "get_provider", lambda *a, **k: provider
        )
    if generator is not None:
        monkeypatch.setattr(
            _seam(api_module, "answer_mod"), "default_generator", lambda *a, **k: generator
        )
    with TestClient(api_module.app, raise_server_exceptions=False) as client:
        yield client


def _fake_generator(text: str = GENERATED):
    """A `generate_fn` seam double that records the prompts it is handed."""
    prompts: list[str] = []

    def generate(prompt: str) -> str:
        prompts.append(prompt)
        return text

    generate.prompts = prompts
    return generate


def _tripwire_generator():
    def generate(prompt: str) -> str:  # pragma: no cover - tripwire
        raise AssertionError(
            "the generator must not be called: a pre-generation refusal spends no tokens"
        )

    generate.prompts = []
    return generate


def _record_answer_calls(monkeypatch, api_module) -> list[dict]:
    """Wrap `answer_mod.answer` in a recorder that delegates to the REAL
    implementation, normalising positional/keyword call styles through the
    real signature so the assertions never depend on how `api.py` spells the
    call."""
    calls: list[dict] = []
    signature = inspect.signature(_REAL_ANSWER)

    def recorder(*args, **kwargs):
        bound = signature.bind(*args, **kwargs)
        bound.apply_defaults()
        calls.append(dict(bound.arguments))
        return _REAL_ANSWER(*args, **kwargs)

    monkeypatch.setattr(_seam(api_module, "answer_mod"), "answer", recorder)
    return calls


def _assert_flat_503(resp, *, contains: str | None = None) -> str:
    """Assert the frozen degradation-rung shape and return the message."""
    assert resp.status_code == 503, f"expected a 503 rung, got {resp.status_code}: {resp.text}"
    body = resp.json()
    assert set(body.keys()) == {"error"}, (
        f"503 rungs are a FLAT {{'error': ...}} JSONResponse, never HTTPException's "
        f"{{'detail': ...}} wrapper (test_api.py's AC-5 section): {sorted(body)}"
    )
    assert isinstance(body["error"], str)
    if contains is not None:
        assert contains.lower() in body["error"].lower(), (
            f"the rung must name its condition; {body['error']!r} does not mention {contains!r}"
        )
    return body["error"]


def _result_doc_ids(resp) -> list[str]:
    return [result["doc_id"] for result in resp.json()["results"]]


def _corrupt_store(tmp_path: Path, provider: ScriptedProvider) -> Path:
    """A store that loads as `CorruptStore` (T-021): a structurally valid
    `entries.json` beside an unreadable `matrix.npy`."""
    store_dir = _build_store(tmp_path, provider, name="corrupt_embeddings")
    (store_dir / "matrix.npy").write_bytes(b"this is not a numpy array")
    return store_dir


