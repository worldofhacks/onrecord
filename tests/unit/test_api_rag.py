def _seam(api_module, name: str):
    """Return `onrecord.api`'s module-level seam `name`, failing cleanly when
    the unlock has not wired it yet.

    Without this, every seam-swapping test would die with an
    `AttributeError: module 'onrecord.api' has no attribute 'embeddings'`
    traceback against the un-unlocked module -- an ERROR, not a readable RED.
    Mirrors `test_api.py`'s `_require_module_spec` idiom one level down.
    """
    if not hasattr(api_module, name):
        pytest.fail(
            f"onrecord.api must expose the module-level seam `{name}` "
            f"(see tests/unit/test_api_rag.py's MODULE SEAMS section) -- "
            f"resolved fresh per request so tests can monkeypatch it"
        )
    return getattr(api_module, name)


class ScriptedProvider:
    """A hand-scriptable `EmbeddingProvider` (T-021's Protocol: `model`,
    `dim`, `embed(texts) -> float32 (len(texts), dim)` in input order).

    Records every call, so "the corpus is embedded once up front, never at
    query time" is measured rather than assumed, and REFUSES unscripted text
    so a fixture drift shows up as a loud AssertionError instead of a
    silently wrong vector.
    """

    dim = 4

    def __init__(self, model: str = "scripted-embed-v1"):
        self.model = model
        self.calls: list[list[str]] = []

    def embed(self, texts: list[str]) -> np.ndarray:
        batch = list(texts)
        self.calls.append(batch)
        missing = [text for text in batch if text not in VECTORS]
        if missing:
            raise AssertionError(f"ScriptedProvider was asked to embed unscripted {missing[0]!r}")
        return np.stack([np.asarray(VECTORS[text], dtype=np.float32) for text in batch])


class TripwireProvider:
    """A provider seam that must never be reached (keyless-lexical
    guarantee). Structurally a provider so nothing fails for the wrong
    reason before the tripwire itself fires."""

    model = "tripwire-must-not-be-resolved"
    dim = 4

    def embed(self, texts: list[str]) -> np.ndarray:  # pragma: no cover - tripwire
        raise AssertionError("the lexical path must never embed anything")


