def test_register_user_sends_signed_request_and_returns_user_secret():
    portfolio = _module()
    seen = {}

    def handler(request: httpx.Request) -> httpx.Response:
        seen["method"] = request.method
        seen["path"] = request.url.path
        seen["query"] = parse_qs(request.url.query.decode("ascii"))
        seen["body"] = json.loads(request.content.decode("utf-8"))
        seen["signature"] = request.headers.get("Signature")
        seen["expected_signature"] = portfolio._sign(
            CONSUMER_KEY,
            request.url.path,
            request.url.query.decode("ascii"),
            json.loads(request.content.decode("utf-8")),
        )
        return _json_response({"userId": USER_ID, "userSecret": USER_SECRET})

    secret = portfolio.register_user(
        CLIENT_ID, CONSUMER_KEY, USER_ID, transport=httpx.MockTransport(handler)
    )
    assert secret == USER_SECRET
    assert seen["method"] == "POST"
    assert seen["path"] == "/api/v1/snapTrade/registerUser"
    assert seen["body"] == {"userId": USER_ID}
    assert set(seen["query"]) == {"clientId", "timestamp"}
    assert seen["query"]["clientId"] == [CLIENT_ID]
    assert seen["query"]["timestamp"][0].isdigit()
    assert seen["signature"] == seen["expected_signature"]


def test_login_url_defaults_to_read_connection_and_returns_portal_url():
    portfolio = _module()
    portal = "https://app.snaptrade.com/connect/abc123"
    seen = {}

    def handler(request: httpx.Request) -> httpx.Response:
        seen["path"] = request.url.path
        seen["query"] = parse_qs(request.url.query.decode("ascii"))
