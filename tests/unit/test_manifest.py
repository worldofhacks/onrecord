"""Failing tests for T-018 — corpus-version manifest (tickets/T-018.md
AC-1..AC-5): `--version N` on `build_corpus`, `manifest.json` written to
BOTH the snapshot out dir and the index-out dir, `MANIFEST_FILENAME` /
`read_manifest` as public API, `onrecord.eval.run._corpus_version()` reading
that manifest via `ONRECORD_INDEX`, and the Makefile `ingest` recipe's `V`/
`RAW` wiring.

Frozen after the Test Agent hands off: do not edit this file to make an
implementation pass — fix `onrecord/ingest/build_corpus.py`,
`onrecord/eval/run.py`, or `Makefile` instead.

Run with:
    uv run pytest tests/unit/test_manifest.py -v

===========================================================================
Test-Agent-pinned decisions (not otherwise nailed down by tickets/T-018.md)
===========================================================================

1. **`--version` / `--out` interaction**: `--version` is an int CLI arg
   (default `1`). `--out`'s default becomes `corpus/v{version}` (relative to
   cwd) whenever `--out` is not explicitly passed — this holds even when
   `--version` itself is omitted (falls back to its own default `1`, giving
   the byte-compatible `corpus/v1`). An explicit `--out` always wins over
   the derived default, regardless of `--version`.

2. **`--index-out`'s default is NOT versioned.** It stays the existing
   unversioned `artifacts/index` regardless of `--version` — this is the
   single "live" index location `onrecord.eval.run` / `onrecord.api` read
   (`DEFAULT_INDEX_PATH` / `ONRECORD_INDEX`, both unversioned); the new
   `manifest.json` inside it is precisely what lets those readers learn
   which corpus version built the live index without themselves needing to
   track a version number.

3. **`created_at` format**: a string parseable via `datetime.fromisoformat`
   (after normalizing a trailing `Z` to `+00:00`) whose `utcoffset()` is
   exactly `timedelta(0)` — i.e. an explicit UTC instant, not a naive
   timestamp merely assumed to be UTC.

4. **Makefile `ingest` recipe conditional-RAW passthrough** is pinned to the
   single-command GNU Make idiom `$(if $(RAW),--raw-dir $(RAW))` appended
   after `--version $(V)` on the existing `uv run python -m
   onrecord.ingest.build_corpus` line — matches the ticket's own literal
   phrasing ("target runs `... --version $(V)` plus `--raw-dir $(RAW)` when
   `RAW` is set") describing one recipe command line, not a duplicated
   `ifdef`/`else` recipe.

5. **AC-4's "no manifest -> unversioned" sub-case is a regression guard**
   (ticket's own parenthetical) and is EXPECTED to already pass against
   today's stub `_corpus_version()`, which unconditionally returns
   `"unversioned"` regardless of `ONRECORD_INDEX`. Only the paired
   "manifest present -> real version" test is a genuine RED assertion for
   this AC; the regression-guard test is kept as an explicit pin so a
   future regression (e.g. raising instead of falling back) is caught, and
   is called out here so its pre-existing green status isn't mistaken for a
   broken test.
"""

