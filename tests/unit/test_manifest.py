def test_manifest_git_sha_matches_real_head_when_cwd_is_a_git_repo(tmp_path, monkeypatch):
    # spec(T-018:AC-1) -- catches a lazy implementation that always emits
    # the "unknown" placeholder even when a real git HEAD is available
    subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True)
    subprocess.run(["git", "config", "user.email", "test@example.com"], cwd=tmp_path, check=True)
    subprocess.run(["git", "config", "user.name", "Test"], cwd=tmp_path, check=True)
    subprocess.run(["git", "commit", "--allow-empty", "-q", "-m", "init"], cwd=tmp_path, check=True)
    expected_sha = subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=tmp_path, capture_output=True, text=True, check=True
    ).stdout.strip()

    monkeypatch.chdir(tmp_path)
    raw_dir = tmp_path / "raw"
    _write_raw_dir(raw_dir, _FIXTURE_DOCS)

    build_corpus.main(["--raw-dir", str(raw_dir)])

    manifest = build_corpus.read_manifest(Path.cwd() / "corpus" / "v1")
    assert manifest["git_sha"] == expected_sha
    assert manifest["git_sha"] != "unknown"


def test_manifest_created_at_is_iso8601_utc_timestamp(tmp_path, monkeypatch):
    # spec(T-018:AC-1)
    monkeypatch.chdir(tmp_path)
    raw_dir = tmp_path / "raw"
    _write_raw_dir(raw_dir, _FIXTURE_DOCS)

    before = datetime.now(UTC)
    build_corpus.main(["--raw-dir", str(raw_dir)])
    after = datetime.now(UTC)

    manifest = build_corpus.read_manifest(Path.cwd() / "corpus" / "v1")
    created_at = manifest["created_at"]
    assert isinstance(created_at, str)
    parsed = datetime.fromisoformat(created_at.replace("Z", "+00:00"))
    assert parsed.utcoffset() == timedelta(0), f"created_at not UTC-labeled: {created_at!r}"
    assert before <= parsed <= after


