def _read_makefile_text() -> str:
    makefile_path = Path(__file__).resolve().parents[2] / "Makefile"
    return makefile_path.read_text()


def _ingest_recipe_block(makefile_text: str) -> str:
    """Extract the `ingest:` target's tab-indented recipe lines."""
    lines = makefile_text.splitlines()
    for i, line in enumerate(lines):
        if line.startswith("ingest:"):
            block_lines = []
            for follow in lines[i + 1 :]:
                if not follow.startswith("\t"):
                    break
                block_lines.append(follow)
            return "\n".join(block_lines)
    raise AssertionError(f"no 'ingest:' target found in Makefile:\n{makefile_text}")


def test_makefile_ingest_recipe_passes_version_with_v_default_of_1():
    # spec(T-018:AC-5)
    text = _read_makefile_text()
    assert re.search(r"^V\s*\?=\s*1\s*$", text, re.MULTILINE), (
        f"Makefile must declare 'V ?= 1' as a top-level variable default:\n{text}"
    )
    block = _ingest_recipe_block(text)
    assert re.search(r"--version\s+\$\(V\)", block), (
        f"ingest recipe must pass --version $(V):\n{block}"
    )


def test_makefile_ingest_recipe_conditionally_passes_raw_dir_when_raw_is_set():
    # spec(T-018:AC-5)
    text = _read_makefile_text()
    block = _ingest_recipe_block(text)
    assert re.search(r"\$\(if\s+\$\(RAW\)\s*,\s*--raw-dir\s+\$\(RAW\)\)", block), (
        f"ingest recipe must conditionally pass --raw-dir $(RAW) only when RAW is "
        f"set (Test-Agent-pinned '$(if $(RAW),--raw-dir $(RAW))' idiom):\n{block}"
    )


