def _write_raw_dir(raw_dir: Path, docs: list[Doc]) -> None:
    path = raw_dir / "batch.jsonl"
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as fh:
        for doc in docs:
            fh.write(json.dumps(asdict(doc)) + "\n")


