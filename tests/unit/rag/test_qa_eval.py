def test_answer_recall_hand_computed_including_chunk_resolver_path():
    # spec(T-025:AC-3)
    qa_eval = _import_qa_eval_module()
    qa_rows = [
        _qa_row("r1", "q-alpha", ["yt:AbCdEfGhIjK:seg005", "yt:AbCdEfGhIjK:seg009"]),
        _qa_row("r2", "q-beta", ["yt:ZzYyXxWwVvU:seg006"]),
        _qa_row("r3", "q-gamma", ["yt:MiXeDcAsE:seg007"]),
    ]

    def retrieve_fn(question: str) -> list[str]:
        return {
            "q-alpha": ["yt:AbCdEfGhIjK:seg005", "yt:other:seg001"],
            "q-beta": ["yt:ZzYyXxWwVvU:seg005+w3"],
            "q-gamma": ["yt:totally:unrelated"],
        }[question]

    def chunk_doc_ids(chunk_id: str) -> list[str]:
        if chunk_id == "yt:ZzYyXxWwVvU:seg005+w3":
            return ["yt:ZzYyXxWwVvU:seg005", "yt:ZzYyXxWwVvU:seg006", "yt:ZzYyXxWwVvU:seg007"]
        return [chunk_id]

    result = qa_eval.answer_recall(qa_rows, retrieve_fn, k=10, chunk_doc_ids=chunk_doc_ids)

    assert result["mean_recall"] == pytest.approx(0.5)
    assert result["k"] == 10
    assert result["n_queries"] == 3
    assert result["per_query"] == [
        {"qa_id": "r1", "recall": pytest.approx(0.5)},
        {"qa_id": "r2", "recall": pytest.approx(1.0)},
        {"qa_id": "r3", "recall": pytest.approx(0.0)},
    ]


