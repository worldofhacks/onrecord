def test_load_qa_invalid_json_line_errors_naming_line_number(tmp_path):
    # spec(T-025:AC-1) -- adversarial: a raw, unwrapped `json.JSONDecodeError`
    # is itself a `ValueError` subclass and would satisfy a naive
    # `pytest.raises(ValueError)` check, but its own `.lineno`/message ("line
    # 1 column N") describe a position WITHIN the single malformed line
    # string handed to `json.loads`, not this file's own 1-indexed line
    # count -- a raw leak would misname/mislead about which physical line of
    # qa.jsonl is broken. The loader must re-raise its OWN ValueError naming
    # the real file line number, not let json's exception escape unwrapped.
    qa_eval = _import_qa_eval_module()
    good = json.dumps(_qa_row("qa1", "q1", ["yt:MiXeDcAsE:seg007"]))
    path = tmp_path / "qa.jsonl"
    _write_lines(path, [good, "{not valid json"])

    with pytest.raises(ValueError) as exc:
        qa_eval.load_qa(path)
    assert not isinstance(exc.value, json.JSONDecodeError), (
        "a raw json.JSONDecodeError must not leak through unwrapped -- its own "
        "line/column numbers do not describe this file's line count"
    )
    assert "2" in str(exc.value), "the wrapping error must name this file's real line number (2)"


