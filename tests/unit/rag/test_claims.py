def test_three_sentence_paragraph_segments_with_each_marker_on_its_own_sentence():
    # spec(T-027:AC-1)
    claims_mod = _claims_module()
    text = (
        "Dominion filed for a rate increase. [1] "
        "Regulators requested more data. [2] "
        "The hearing concluded without a ruling."
    )

    claims = claims_mod.split_claims(text)

    assert len(claims) == 3
    assert claims[0].startswith("Dominion filed for a rate increase.")
    assert claims[1].startswith("Regulators requested more data.")
    assert claims[2] == "The hearing concluded without a ruling."
    # Each marker stays attached to the sentence it follows -- never orphaned
    # into the next claim, and never leaking into an unrelated one.
    assert "[1]" in claims[0]
    assert "[1]" not in claims[1]
    assert "[1]" not in claims[2]
    assert "[2]" in claims[1]
    assert "[2]" not in claims[0]
    assert "[2]" not in claims[2]


