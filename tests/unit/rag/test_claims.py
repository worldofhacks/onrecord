def _require_module_spec(name: str, fail_message: str):
    try:
        spec = importlib.util.find_spec(name)
    except ModuleNotFoundError:
        spec = None
    if spec is None:
        pytest.fail(fail_message)
    return spec


def _claims_module():
    _require_module_spec("onrecord.rag.claims", "onrecord.rag.claims missing")
    import onrecord.rag.claims as claims_module

    return claims_module


