def _assert_pinned_shape(result) -> None:
    """The PINNED-FOR-THURSDAY contract, asserted EXACTLY at every level."""
    assert isinstance(result, dict), f"answer() returns a dict; got {type(result)!r}"
    assert set(result) == PINNED_TOP_LEVEL_KEYS, (
        "the /api/answer response shape is LOCKED (tests/unit/test_api.py "
        "PINNED-FOR-THURSDAY, parsed directly by the UI) — extra or missing "
        f"top-level keys are a contract break; got {sorted(result)}"
    )
    assert isinstance(result["answer_id"], str) and result["answer_id"]
    assert isinstance(result["text"], str)
    assert isinstance(result["citations"], list)
    assert isinstance(result["retrieved"], list)

    for citation in result["citations"]:
        assert set(citation) == PINNED_CITATION_KEYS, (
            f"citation entries are exactly {sorted(PINNED_CITATION_KEYS)}; got {sorted(citation)}"
        )
        assert isinstance(citation["n"], int) and not isinstance(citation["n"], bool)
        assert isinstance(citation["doc_id"], str)
        assert isinstance(citation["deep_link"], str)
        assert isinstance(citation["snippet"], str)

    for entry in result["retrieved"]:
        assert set(entry) == PINNED_RETRIEVED_KEYS, (
            "retrieved entries are the 9-key /api/search result shape plus "
            f"'cited' (no 'speaker' — locked); got {sorted(entry)}"
        )
        assert isinstance(entry["score"], float), (
            f"score is a JSON float; got {type(entry['score'])!r}"
        )
        assert isinstance(entry["cited"], bool)

    grounding = result["grounding"]
    assert set(grounding) == PINNED_GROUNDING_KEYS, (
        f"grounding is exactly {sorted(PINNED_GROUNDING_KEYS)}; got {sorted(grounding)}"
    )
    assert grounding["status"] in {"grounded", "partial", "ungrounded"}
    assert isinstance(grounding["supported_claims"], int)
    assert isinstance(grounding["total_claims"], int)

