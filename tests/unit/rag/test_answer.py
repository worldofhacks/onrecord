def _require_module_spec(name: str, fail_message: str):
    """Return the module spec for `name`, or fail cleanly via pytest.fail.

    `importlib.util.find_spec` raises ModuleNotFoundError (rather than
    returning None) when a parent package in a dotted name is itself missing,
    so both "not found" cases are normalized into one clean assertion-style
    failure — never an uncaught ImportError, never a collection error.
    """
    try:
        spec = importlib.util.find_spec(name)
    except ModuleNotFoundError:
        spec = None
    if spec is None:
        pytest.fail(fail_message)
    return spec


def _module():
    _require_module_spec(
        "onrecord.rag.answer",
        "onrecord.rag.answer missing (T-023 target module — expected RED until "
        "the Implementation Agent lands it)",
    )
    import onrecord.rag.answer as answer_module

    return answer_module


def _attr(name: str):
    mod = _module()
    if not hasattr(mod, name):
        pytest.fail(f"onrecord.rag.answer.{name} missing (T-023 public API)")
    return getattr(mod, name)


