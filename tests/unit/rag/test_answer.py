# Letters + space only: no digits (so a body can never look like a bare list
# enumerator), no brackets, no underscore (so the SENTINEL can never be
# generated by accident).
_BODY_ALPHABET = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ "
_body_strategy = st.text(alphabet=_BODY_ALPHABET, min_size=1, max_size=12).filter(
    lambda body: body.strip() != ""
)


@st.composite
def _generated_answers(draw):
    """A generated answer mixing valid, dangling and unterminated markers.

    NOTE ON SEGMENTATION: the expectations this property checks are derived
    from the RETURNED text via the real `split_claims`, never from an assumed
    segmentation of the generated text — so an abbreviation- or
    enumerator-shaped body cannot poison the property (the T-027 deflake
    class). Only the CITATION ORDER expectation comes from the generator side,
    and that is order-preserving under dangling-marker stripping.
    """
    chunk_count = draw(st.integers(min_value=1, max_value=4))
    sentences = draw(st.integers(min_value=1, max_value=5))
    bodies = draw(st.lists(_body_strategy, min_size=sentences, max_size=sentences))
    kinds = draw(
        st.lists(
            st.sampled_from(["none", "valid", "dangling", "unterminated"]),
            min_size=sentences,
            max_size=sentences,
        )
    )
    valid_ns = draw(
        st.lists(
            st.integers(min_value=1, max_value=chunk_count),
            min_size=sentences,
            max_size=sentences,
        )
    )
    dangling_ns = draw(
        st.lists(
            st.integers(min_value=chunk_count + 1, max_value=chunk_count + 6),
            min_size=sentences,
            max_size=sentences,
        )
    )

    pieces: list[str] = []
    expected_ns: list[int] = []
    dangling_markers: list[str] = []
    unterminated = 0
    for i in range(sentences):
        piece = f"{bodies[i]}."
        if kinds[i] == "valid":
            piece += f" [{valid_ns[i]}]"
            expected_ns.append(valid_ns[i])
        elif kinds[i] == "dangling":
            piece += f" [{dangling_ns[i]}]"
            dangling_markers.append(f"[{dangling_ns[i]}]")
        elif kinds[i] == "unterminated":
            piece += f" [{valid_ns[i]}"
            unterminated += 1
        pieces.append(piece)

    return " ".join(pieces), chunk_count, expected_ns, dangling_markers, unterminated


@given(data=_generated_answers())
@settings(max_examples=100, deadline=None)
def test_property_citations_and_grounding_stay_consistent_for_any_marker_mix(data):
    # spec(T-023:AC-2)
    generated, chunk_count, expected_ns, dangling_markers, unterminated = data
    chunks = [_synthetic_chunk(i) for i in range(chunk_count)]

    result = _attr("answer")(QUESTION, chunks, FakeGenerator(generated))

    _assert_pinned_shape(result)
    assert result["refusal"] is None

    # Citations: distinct valid ns, first-appearance order.
    seen: list[int] = []
    for n in expected_ns:
        if n not in seen:
            seen.append(n)
    assert _citation_ns(result) == seen

    # Dangling markers never survive; valid and unterminated ones always do.
    # Counted on the brackets themselves so a valid `[2]` cannot vacuously
    # satisfy the check for an unterminated `[2`.
    for marker in dangling_markers:
        assert marker not in result["text"]
    assert result["text"].count("[") == len(expected_ns) + unterminated, (
        f"every valid marker and every unterminated `[n` must survive in the "
        f"text, and only those; got {result['text']!r}"
    )
    assert result["text"].count("]") == len(expected_ns)

    # Grounding is recomputed from the RETURNED text with the shared
    # segmentation authority.
    text = result["text"]
    total = len(split_claims(text))
    supported = _supported_claim_count(text, chunk_count)
    assert result["grounding"]["total_claims"] == total
    assert result["grounding"]["supported_claims"] == supported
    expected_status = (
        "grounded"
        if supported == total and total > 0
        else "partial"
        if supported > 0
        else "ungrounded"
    )
    assert result["grounding"]["status"] == expected_status

    # cited flags follow the citations, never the other way round.
    cited_ids = {citation["doc_id"] for citation in result["citations"]}
    for entry in result["retrieved"]:
        assert entry["cited"] is (entry["doc_id"] in cited_ids)


