class FakeGenerator:
    """A scripted `generate_fn`. Records every prompt it is handed.

    Its output is a TEST INPUT, not model behaviour: nothing in this suite
    asserts the prose is good, only that our deterministic post-processing
    handles it exactly as pinned.
    """

    def __init__(self, text: str):
        self.text = text
        self.prompts: list[str] = []

    def __call__(self, prompt: str) -> str:
        self.prompts.append(prompt)
        return self.text

    @property
    def calls(self) -> int:
        return len(self.prompts)


class ExplodingGenerator:
    """A `generate_fn` that PROVES it was never called, two ways.

    It raises on call (so a refusal path that generates first fails loudly with
    a named reason) AND counts calls (so an implementation that swallows the
    exception is still caught by the count assertion).
    """

    def __init__(self):
        self.prompts: list[str] = []

    def __call__(self, prompt: str) -> str:
        self.prompts.append(prompt)
        raise AssertionError(
            "generate_fn was called on a retrieval-confidence refusal path — the "
            "refusal is decided BEFORE generation (tickets/T-023.md AC-4); "
            "spending a generation call on a known-refusal is the exact cost the "
            "deterministic gate exists to avoid"
        )

    @property
    def calls(self) -> int:
        return len(self.prompts)


