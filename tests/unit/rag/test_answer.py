def _supported_claim_count(text: str, chunk_count: int) -> int:
    """Recompute grounding's numerator from the RETURNED text, using the real
    segmentation authority — the structural cross-check for every hand-computed
    number in this file."""
    supported = 0
    for claim in split_claims(text):
        ns = [int(raw) for raw in _VALID_MARKER_RE.findall(claim)]
        if any(1 <= n <= chunk_count for n in ns):
            supported += 1
    return supported


_PROMPT_MARKER_RE = re.compile(r"\[(\d+)\]")


def _owning_block(prompt: str, needle: str) -> int | None:
    """The number of the numbered block whose marker most closely PRECEDES
    `needle` — i.e. the block `needle` belongs to.

    Nearest-preceding-marker association is deliberately tolerant of the
    instruction block's own wording (which talks about `[n]`, with a literal
    `n`, never a digit) and of whatever separators/metadata the implementer
    puts inside a block.

    IMPLEMENTER HEADS-UP (test-review M-7): this association does imply a
    MARKER-FIRST block layout — the `[i]` marker opens its block, with the
    chunk's deep_link and text after it (`[1] 2026-04-28 | … | https://…\\n
    <text>`). A layout that trails the marker after the text
    (`<text>\\n[1] source: …`) would fail AC-6 even though the ticket only
    says each block "carr[ies] its chunk's deep_link". Marker-first is the
    shape the ticket's own "numbered context blocks `[1]..[m]`" describes and
    the one the frozen tests pin.
    """
    at = prompt.find(needle)
    assert at != -1, f"expected {needle!r} to appear verbatim in the prompt"
    owner = None
    for match in _PROMPT_MARKER_RE.finditer(prompt):
        if match.start() >= at:
            break
        owner = int(match.group(1))
    return owner


@contextlib.contextmanager
def _library_loggers_unmuted():
    """Reproduce the repo's own process-wide INFO logging (LESSONS T-014).

    onrecord's entrypoints call `logging.basicConfig(level=INFO)` and library
    loggers are NOTSET by default, so they inherit root. The baseline —
    including root's handler list — is restored afterwards so a `basicConfig`
    that is NOT a no-op (e.g. under `-p no:logging`) cannot leak a handler into
    the rest of the session.
    """
    root = logging.getLogger()
    previous_root_level = root.level
    previous_handlers = root.handlers[:]
    library = [logging.getLogger(name) for name in ("httpx", "httpcore", "anthropic")]
    previous = [(lg, lg.level, lg.propagate) for lg in library]
    logging.basicConfig(level=logging.INFO)
    root.setLevel(logging.INFO)
    for lg in library:
        lg.setLevel(logging.NOTSET)
        lg.propagate = True
    try:
        yield
    finally:
        root.setLevel(previous_root_level)
        root.handlers[:] = previous_handlers
        for lg, level, propagate in previous:
            lg.setLevel(level)
            lg.propagate = propagate


