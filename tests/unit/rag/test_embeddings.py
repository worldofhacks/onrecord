def test_resumed_store_equals_the_never_crashed_store(tmp_path):
    # spec(T-021:AC-8)
    pairs = _pairs(6)
    checkpoint_dir = tmp_path / "ckpt"
    crashed = _new_store()
    with pytest.raises(ProviderBoom):
        crashed.embed_corpus(
            pairs, FakeProvider(fail_on_call=3), checkpoint_dir=checkpoint_dir, checkpoint_every=2
        )
    resumed = _load_store(checkpoint_dir)
    resumed.embed_corpus(pairs, FakeProvider(), checkpoint_dir=checkpoint_dir, checkpoint_every=2)

    clean = _new_store()
    clean.embed_corpus(pairs, FakeProvider())

    assert resumed.matrix.shape == clean.matrix.shape == (6, 4)
    assert np.array_equal(resumed.matrix, clean.matrix), (
        "a resumed run must be byte-identical to an uninterrupted one — same rows, "
        "same first-appearance order"
    )
    hashes = _hashes_for(pairs)
    assert [resumed.entry_for(h) for h in hashes] == [clean.entry_for(h) for h in hashes]
