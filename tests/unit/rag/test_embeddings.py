def _content_hash(model: str, dim: int, text: str) -> str:
    """The frozen cache key: sha256("<model>\\n<dim>\\n<text>") hexdigest."""
    return hashlib.sha256(f"{model}\n{dim}\n{text}".encode()).hexdigest()


def _pairs(n: int, prefix: str = "t") -> list[tuple[str, str]]:
    """`n` (chunk_id, text) pairs, all texts distinct."""
    return [(f"c{i}", f"{prefix} {i}") for i in range(n)]


def _ids(pairs: list[tuple[str, str]]) -> list[str]:
    return [chunk_id for chunk_id, _text in pairs]


def _l2(vec: np.ndarray) -> np.ndarray:
    vec = np.asarray(vec, dtype=np.float32)
    return vec / np.linalg.norm(vec)


def _entries_payload(entries: dict[str, dict], model: str = FAKE_MODEL, dim: int = 4) -> dict:
    return {"model": model, "dim": dim, "entries": entries}


def _write_raw_store(path: Path, matrix: np.ndarray, payload: dict) -> None:
    """Write a store's two files by hand (AC-7 corrupt-store fixtures)."""
    path.mkdir(parents=True, exist_ok=True)
    np.save(path / "matrix.npy", matrix)
    (path / "entries.json").write_text(json.dumps(payload), encoding="utf-8")


def _valid_raw_store(path: Path, rows: int = 3, dim: int = 4) -> tuple[np.ndarray, dict]:
    """A hand-written, structurally valid store — the AC-7 baseline.

    Deliberately written with EXACTLY the three required top-level keys, so
    `load` may not depend on any additional field of its own invention.
    """
    matrix = np.stack([_l2(_fake_vector(f"t {i}", dim, FAKE_MODEL)) for i in range(rows)]).astype(
        np.float16
    )
    entries = {
        f"c{i}": {"row": i, "content_hash": _content_hash(FAKE_MODEL, dim, f"t {i}")}
        for i in range(rows)
    }
    payload = _entries_payload(entries, model=FAKE_MODEL, dim=dim)
    _write_raw_store(path, matrix, payload)
    return matrix, payload


def _build_cosine_store(vectors: list[list[float]]):
    """A real EmbeddingStore holding exactly `vectors` (normalized, fp16)."""
    texts = [f"cos-text-{i}" for i in range(len(vectors))]
    provider = ScriptedProvider(dict(zip(texts, vectors, strict=True)))
    store = _new_store()
    store.embed_corpus([(f"cos-{i}", t) for i, t in enumerate(texts)], provider)
    return store


def _embed_until_crash(store, pairs, provider, checkpoint_dir, checkpoint_every):
    """Run `embed_corpus` expecting the scripted provider failure.

    Fails with an explanatory message (rather than an opaque shape error)
    when the provider's scripted 3rd call is never reached — which happens
    exactly when batches are larger than `checkpoint_every` (review I-2).
    """
    try:
        store.embed_corpus(
            pairs,
            provider,
            checkpoint_dir=checkpoint_dir,
            checkpoint_every=checkpoint_every,
        )
    except ProviderBoom:
        return
    pytest.fail(
        f"the FakeProvider was scripted to fail on its 3rd call and embed_corpus "
        f"never reached it: batches must hold AT MOST checkpoint_every "
        f"({checkpoint_every}) items so a checkpoint can be written every "
        f"{checkpoint_every} newly-embedded items. Batch sizes were "
        f"{[len(b) for b in provider.calls]}."
    )


def _marker_value(text: str) -> float:
    """Recover the ordinal encoded in a `doc-<i>` text (0.0 if absent)."""
    tail = text.rsplit("-", 1)[-1]
    return float(tail) if tail.isdigit() else 0.0


def _openai_handler(
    dim: int,
    requests: list[httpx.Request],
    statuses: list[int] | None = None,
    reverse_data: bool = False,
):
    """MockTransport handler: records requests, replies OpenAI-shaped.

    Each returned embedding is `[<ordinal of the text>, 0.0, 0.0, ...]` so a
    row's identity is readable from its first component — that is how the
    "row order == input order" contract is asserted across a batch split.
    `statuses` is a queue of status codes (200 once exhausted).
    """
    queue = list(statuses or [])
    tail = [0.0] * (dim - 1)

    def handler(request: httpx.Request) -> httpx.Response:
        requests.append(request)
        status = queue.pop(0) if queue else 200
        if status != 200:
            return httpx.Response(status, json={"error": {"message": "upstream boom"}})
        payload = json.loads(request.content)
        texts = payload["input"]
        data = [
            {
                "object": "embedding",
                "index": i,
                "embedding": [_marker_value(text), *tail],
            }
            for i, text in enumerate(texts)
        ]
        if reverse_data:
            data = list(reversed(data))
        return httpx.Response(
            200,
            json={
                "object": "list",
                "data": data,
                "model": payload.get("model"),
                "usage": {"prompt_tokens": len(texts), "total_tokens": len(texts)},
            },
        )

    return handler


