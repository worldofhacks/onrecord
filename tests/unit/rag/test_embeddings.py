@contextlib.contextmanager
def _library_loggers_unmuted():
    """Reproduce the repo's own process-wide INFO logging (LESSONS T-014).

    onrecord's ingest entrypoints call `logging.basicConfig(level=INFO)`, and
    httpx's own logger is NOTSET by default so it inherits root. The baseline
    is restored afterwards — including root's handler list, so a
    `basicConfig` that is NOT a no-op (e.g. under `-p no:logging`, where
    pytest has not installed a root handler) cannot leak a StreamHandler into
    the rest of the session (review M-6). An implementation that
    silences/redacts library loggers AROUND its own keyed request still wins,
    because that happens inside the call, after this setup.
    """
    root = logging.getLogger()
    previous_root_level = root.level
    previous_handlers = root.handlers[:]
    library = [logging.getLogger(name) for name in ("httpx", "httpcore", "openai")]
    previous = [(lg, lg.level, lg.propagate) for lg in library]
    logging.basicConfig(level=logging.INFO)
    root.setLevel(logging.INFO)
    for lg in library:
        lg.setLevel(logging.NOTSET)
        lg.propagate = True
    try:
        yield
    finally:
        root.setLevel(previous_root_level)
        root.handlers[:] = previous_handlers
        for lg, level, propagate in previous:
            lg.setLevel(level)
            lg.propagate = propagate


