def test_interrupted_save_leaves_the_previous_store_loadable(tmp_path, monkeypatch):
    # spec(T-021:AC-3)
    # Atomicity asserted by BEHAVIOR, not by spying on os.replace: whatever a
    # crashed save leaves behind, the previously-saved store must still load
    # intact and self-consistent.
    #
    # `np.save` here writes its file and THEN raises ("raising after the first
    # file", per AC-3) — the realistic mid-save crash, where the first file has
    # already hit the disk. That ordering is what makes this test bite in BOTH
    # in-place-write orders: matrix-first leaves a new matrix beside old
    # entries, entries-first leaves new entries beside an old matrix, and both
    # produce a store that is no longer the one this test saved. Only
    # temp-names-then-os.replace survives.
    path = tmp_path / "store"
    first_pairs = _pairs(3)
    first = _new_store()
    first.embed_corpus(first_pairs, FakeProvider())
    first.save(path)
    expected_matrix = np.array(first.matrix, copy=True)

    second = _new_store()
    second.embed_corpus(first_pairs + [("c7", "seven"), ("c8", "eight")], FakeProvider())
    monkeypatch.setattr(np, "save", _save_then_fail)
    with pytest.raises(OSError):
        second.save(path)
    monkeypatch.undo()

    reloaded = _load_store(path)
    assert np.array_equal(reloaded.matrix, expected_matrix), (
        "a save interrupted mid-write must leave the PREVIOUS store fully intact "
        "(write both files to temp names, then os.replace)"
    )
    assert [reloaded.entry_for(h) for h in _hashes_for(first_pairs)] == [
        {"row": 0, "chunk_id": "c0"},
        {"row": 1, "chunk_id": "c1"},
        {"row": 2, "chunk_id": "c2"},
    ]
    assert reloaded.rows_for(_hashes_for([("c7", "seven")])) == [None], (
        "the interrupted save must not have leaked the new run's entries onto the "
        "old matrix — that is exactly the silent mis-map the atomic contract bans"
    )


def _save_then_fail(*args, **kwargs):
    """Let np.save write its file, then blow up — see the test above."""
    _REAL_NP_SAVE(*args, **kwargs)
    raise OSError("simulated crash immediately after np.save wrote its file")


