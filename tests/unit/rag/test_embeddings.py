class ProviderBoom(RuntimeError):
    """Simulated mid-run provider failure (quota exhaustion / flaky host)."""


def _fake_vector(text: str, dim: int, model: str) -> np.ndarray:
    """Deterministic, hash-seeded pseudo-embedding — stable across runs."""
    digest = hashlib.sha256(f"{model}|{dim}|{text}".encode()).digest()
    seed = int.from_bytes(digest[:8], "big")
    rng = np.random.default_rng(seed)
    return rng.standard_normal(dim).astype(np.float32)


class FakeProvider:
    """Hash-seeded deterministic stand-in for a real EmbeddingProvider.

    `calls` records every batch the store ASKED for; `returned` records only
    the batches that actually produced vectors (a batch that raises appears
    in `calls` but not in `returned`) — the AC-8 "nothing is embedded twice"
    assertion is about successfully-embedded texts.
    """

    def __init__(
        self,
        dim: int = 4,
        model: str = FAKE_MODEL,
        fail_on_call: int | None = None,
    ):
        self.dim = dim
        self.model = model
        self.fail_on_call = fail_on_call
        self.calls: list[list[str]] = []
        self.returned: list[list[str]] = []

    def embed(self, texts: list[str]) -> np.ndarray:
        batch = list(texts)
        self.calls.append(batch)
        if self.fail_on_call is not None and len(self.calls) == self.fail_on_call:
            raise ProviderBoom(f"simulated provider failure on batch {self.fail_on_call}")
        self.returned.append(batch)
        if not batch:
            return np.zeros((0, self.dim), dtype=np.float32)
        rows = [_fake_vector(t, self.dim, self.model) for t in batch]
        return np.stack(rows).astype(np.float32)

    @property
    def texts_seen(self) -> list[str]:
        return [t for batch in self.calls for t in batch]

    @property
    def texts_returned(self) -> list[str]:
        return [t for batch in self.returned for t in batch]


class ScriptedProvider:
    """Returns exactly the vector scripted for each text (hand-computable)."""

    def __init__(self, vectors: dict[str, list[float]], model: str = "scripted-model"):
        self.vectors = {k: np.asarray(v, dtype=np.float32) for k, v in vectors.items()}
        self.dim = int(next(iter(self.vectors.values())).shape[0])
        self.model = model
        self.calls: list[list[str]] = []

    def embed(self, texts: list[str]) -> np.ndarray:
        batch = list(texts)
        self.calls.append(batch)
        return np.stack([self.vectors[t] for t in batch]).astype(np.float32)


