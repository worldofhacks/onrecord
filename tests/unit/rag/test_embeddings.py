def test_permuted_store_with_extra_rows_resolves_by_hash_not_position():
    # spec(T-021:AC-2)
    # C-3 adversarial: same 4 texts, different insertion order, PLUS 2 extra
    # rows appended. Row order is first-appearance order across all runs, so
    # position is meaningless; only hash -> row -> chunk_id is authoritative.
    pairs = _pairs(4)
    reference = _new_store()
    reference.embed_corpus(pairs, FakeProvider())

    permuted_pairs = [pairs[2], pairs[0], pairs[3], pairs[1], ("c4", "t 4"), ("c5", "t 5")]
    permuted = _new_store()
    permuted.embed_corpus(permuted_pairs, FakeProvider())

    hashes = _hashes_for(pairs)
    assert reference.rows_for(hashes) == [0, 1, 2, 3]
    assert permuted.rows_for(hashes) == [1, 3, 0, 2], (
        f"rows must follow first-appearance order in THIS store, not the caller's "
        f"pair order; got {permuted.rows_for(hashes)}"
    )
    for (chunk_id, _text), h in zip(pairs, hashes, strict=True):
        entry = permuted.entry_for(h)
        assert entry["chunk_id"] == chunk_id, (
            f"hash -> chunk_id correspondence must survive a permuted, extended "
            f"store: {h[:8]} recorded {entry!r}, expected chunk_id {chunk_id}"
        )
        assert np.array_equal(
            permuted.matrix[entry["row"]], reference.matrix[reference.entry_for(h)["row"]]
        ), f"the vector reached via hash must be identical in both stores for {chunk_id}"
    assert not np.array_equal(permuted.matrix[0], reference.matrix[0]), (
        "the adversarial point: a consumer that indexed positionally (row i == "
        "pairs[i]) would silently read the WRONG chunk's vector here"
    )


def test_swapped_chunk_ids_are_visible_through_entry_for(tmp_path):
    # spec(T-021:AC-2)
    # C-3 adversarial: a store whose hashes all match and whose length checks
    # all pass, but whose recorded chunk_ids have drifted. `len(entries) ==
    # matrix.shape[0]` proves NOTHING — only id-level verification catches it.
    pairs = _pairs(6)
    store = _new_store()
    store.embed_corpus(pairs, FakeProvider())
    path = tmp_path / "store"
    store.save(path)

    entries_path = path / "entries.json"
    entries = json.loads(entries_path.read_text(encoding="utf-8"))
    hashes = _hashes_for(pairs)
    entries[hashes[0]]["chunk_id"], entries[hashes[1]]["chunk_id"] = (
        entries[hashes[1]]["chunk_id"],
        entries[hashes[0]]["chunk_id"],
    )
    entries_path.write_text(json.dumps(entries), encoding="utf-8")

    reloaded = _load_store(path)

    assert len(entries) == reloaded.matrix.shape[0] == 6, (
        "precondition of the adversarial case: the store is structurally valid, "
        "so a length-equality check passes while the alignment is wrong"
    )
    assert reloaded.entry_for(hashes[0])["chunk_id"] == "c1", (
        "entry_for must report the chunk_id RECORDED on disk (not one silently "
        "reconstructed from position), which is what lets a consumer detect drift"
    )
    row = reloaded.matrix[reloaded.entry_for(hashes[0])["row"]].astype(np.float32)
    assert np.allclose(row, _l2(_fake_vector("t 0", 4, FAKE_MODEL)), atol=1e-3), (
        "the vector itself is still 't 0' — the chunk_id is the ONLY signal that "
        "the id-level correspondence broke"
    )


