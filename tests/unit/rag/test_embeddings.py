def test_stored_rows_are_l2_normalized_fp16_of_provider_vectors():
    # spec(T-021:AC-2)
    pairs = _pairs(3)
    provider = FakeProvider()
    store = _new_store()
    store.embed_corpus(pairs, provider)

    assert store.matrix.dtype == np.float16, (
        f"the packed matrix is fp16 (0.78 GB at 265K x 1536 — fp32 would double it): "
        f"got {store.matrix.dtype}"
    )
    for i, (_chunk_id, text) in enumerate(pairs):
        expected = _l2(_fake_vector(text, provider.dim, provider.model))
        row = store.matrix[i].astype(np.float32)
        assert np.allclose(row, expected, atol=1e-3), (
            f"row {i} must be the L2-normalized provider vector within fp16 tolerance: "
            f"{row} != {expected}"
        )
        assert float(np.linalg.norm(row)) == pytest.approx(1.0, abs=2e-3), (
            f"rows are normalized ONCE at ingest so cosine is a plain dot product; "
            f"row {i} has norm {float(np.linalg.norm(row))}"
        )


def test_cache_key_is_dim_scoped_so_a_dim_change_cannot_poison_it():
    # spec(T-021:AC-2)
    # plan-review M-9: same model name, different `dimensions` -> different key.
    text = "identical text at two dimensionalities"
    store = _new_store()
    store.embed_corpus([("c0", text)], FakeProvider(dim=4, model="shared-model"))

    hash_dim4 = _content_hash("shared-model", 4, text)
