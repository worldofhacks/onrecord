def test_interrupted_save_leaves_the_previous_store_loadable(tmp_path, monkeypatch):
    # spec(T-021:AC-3)
    # Atomicity asserted by BEHAVIOR: whatever a crashed save leaves behind,
    # the previously-saved store must still load intact and self-consistent.
    #
    # `np.save` here writes its file and THEN raises ("monkeypatched np.save
    # raising after the first file", per AC-3) — the realistic mid-save crash,
    # where the first file has already hit the disk. That ordering is what
    # makes this bite in BOTH in-place write orders: matrix-first leaves a new
    # matrix beside old entries, entries-first leaves new entries beside an
    # old matrix. Only temp-names-then-os.replace survives.
    path = tmp_path / "store"
    first_pairs = _pairs(3)
    first = _new_store()
    first.embed_corpus(first_pairs, FakeProvider())
    first.save(path)
    expected_matrix = np.array(first.matrix, copy=True)

    second = _new_store()
    second.embed_corpus(first_pairs + [("c7", "seven"), ("c8", "eight")], FakeProvider())
    monkeypatch.setattr(np, "save", _save_then_fail)
    try:
        second.save(path)
    except OSError:
        pass
    else:
        pytest.fail(
            "save() completed even though numpy.save was patched to raise. AC-3 "
            "pins the interruption through `np.save`, so the matrix write must go "
            "through numpy.save(...) — np.lib.format.write_array or a raw file "
            "handle will not trip this test (review M-1)."
        )
    finally:
        monkeypatch.undo()

    reloaded = _load_store(path)
    assert np.array_equal(reloaded.matrix, expected_matrix), (
        "a save interrupted mid-write must leave the PREVIOUS store fully intact "
        "(write both files to temp names, then os.replace)"
    )
    assert [reloaded.entry_for(i) for i in _ids(first_pairs)] == [
        {"row": 0, "content_hash": _content_hash(FAKE_MODEL, 4, "t 0")},
        {"row": 1, "content_hash": _content_hash(FAKE_MODEL, 4, "t 1")},
        {"row": 2, "content_hash": _content_hash(FAKE_MODEL, 4, "t 2")},
    ]
    assert reloaded.rows_for(["c7"]) == [None], (
        "the interrupted save must not have leaked the new run's entries onto the "
        "old matrix — that is exactly the silent mis-map the atomic contract bans"
    )


