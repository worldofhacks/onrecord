@st.composite
def _yt_corpus_and_params(draw):
    pairs = draw(
        st.lists(
            # The upper bound crosses ingest's f"seg{i:03d}" zero-padding
            # boundary on purpose, so "ascending segment order" is exercised
            # as a NUMERIC ordering, not a lexicographic one.
            st.tuples(st.sampled_from([VIDEO_A, VIDEO_B, VIDEO_C]), st.integers(0, 1200)),
            min_size=1,
            max_size=12,
            unique=True,
        )
    )
    window = draw(st.integers(1, 5))
    overlap = draw(st.integers(0, window - 1))
    return [_yt_doc(video, n) for video, n in pairs], window, overlap


@given(_yt_corpus_and_params())
@settings(max_examples=60, deadline=None)
def test_property_overlap_zero_preserves_the_input_id_multiset(case):
    # spec(T-020:AC-4) -- stride == window, so every input doc appears in
    # exactly one chunk, and no id is invented, dropped or duplicated.
    docs, window, _overlap = case
    chunks = _chunk_corpus(docs, window=window, overlap=0)
    constituents = list(chain.from_iterable(c.doc_ids for c in chunks))
    assert sorted(constituents) == sorted(d.id for d in docs)


@given(_yt_corpus_and_params())
@settings(max_examples=60, deadline=None)
def test_property_no_chunk_ever_contains_an_id_absent_from_the_input(case):
    # spec(T-020:AC-4) -- at ANY valid (window, overlap): verbatim echo,
    # never a re-minted, re-cased or reshaped doc id.
    docs, window, overlap = case
