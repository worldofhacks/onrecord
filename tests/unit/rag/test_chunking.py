def _by_id(chunks) -> dict:
    return {chunk.chunk_id: chunk for chunk in chunks}


def _doc_ids_map(chunks) -> dict:
    return {chunk.chunk_id: list(chunk.doc_ids) for chunk in chunks}


def _windows_of(chunks, video: str) -> list[tuple[str, ...]]:
    """Constituent-id tuples of the chunks belonging to `video`, in the order
    `chunk_corpus` emitted them (relative order WITHIN one video is pinned;
    the global list order is not)."""
    prefix = f"yt:{video}:"
    return [tuple(c.doc_ids) for c in chunks if c.doc_ids[0].startswith(prefix)]


def _seg_numbers(doc_ids) -> list[int]:
    return [int(doc_id.rsplit(":seg", 1)[1]) for doc_id in doc_ids]


def _judgment_row(query_id: str, query: str, doc_id: str, grade: int) -> dict:
    return {
        "query_id": query_id,
        "query": query,
        "criterion": "on-the-record discussion of the queried topic",
        "doc_id": doc_id,
        "grade": grade,
    }


def _write_judgments(path: Path, rows: list[dict]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as fh:
        for row in rows:
            fh.write(json.dumps(row) + "\n")
    return path


