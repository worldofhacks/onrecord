_PROSE_ALPHABET = "abcdefghijklmnopqrstuvwxyz ABCXYZ.,:\n"


@st.composite
def _judge_outputs(draw):
    """Protocol-clean JSON wrapped in brace-free prose (the real shape)."""
    verdict = draw(st.sampled_from(VERDICT_ENUM))
    evidence = draw(st.one_of(st.none(), st.integers(min_value=1, max_value=10)))
    prefix = draw(st.text(alphabet=_PROSE_ALPHABET, max_size=40))
    suffix = draw(st.text(alphabet=_PROSE_ALPHABET, max_size=40))
    body = json.dumps({"verdict": verdict, "evidence_chunk": evidence})
    return f"{prefix}{body}{suffix}", verdict, evidence


