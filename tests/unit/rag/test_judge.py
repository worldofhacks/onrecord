class ClaimKeyedJudge:
    """A `judge_fn` scripted per claim, matched by a unique claim substring.

    `script` maps a substring that appears in exactly one claim's prompt to
    either a raw response string or an exception INSTANCE to raise.

    A fixture miss is recorded in `.misses` and answered with a neutral
    garbage string rather than raised: `judge_answer` catches exceptions from
    `judge_fn` by contract, so a raised AssertionError would be silently
    converted into an "error" verdict and the test would pass for the wrong
    reason. Every test using this double asserts `.misses == []`.
    """

    def __init__(self, script: dict):
        self.script = script
        self.prompts: list[str] = []
        self.misses: list[str] = []

    def __call__(self, prompt: str) -> str:
        self.prompts.append(prompt)
        matched = [key for key in self.script if key in prompt]
        if len(matched) != 1:
            self.misses.append(f"{len(matched)} script keys matched this prompt: {prompt!r}")
            return "FIXTURE-MISS"
        response = self.script[matched[0]]
        if isinstance(response, BaseException):
            raise response
        return response

    @property
    def call_count(self) -> int:
        return len(self.prompts)


class ConstantJudge:
    """A `judge_fn` returning one fixed raw response for every prompt."""

    def __init__(self, response: str):
        self.response = response
        self.prompts: list[str] = []

    def __call__(self, prompt: str) -> str:
        self.prompts.append(prompt)
        return self.response

    @property
    def call_count(self) -> int:
        return len(self.prompts)


class NeverCalledJudge:
    """A `judge_fn` that records calls; used for call-count-zero assertions."""

    def __init__(self):
        self.prompts: list[str] = []

    def __call__(self, prompt: str) -> str:
        self.prompts.append(prompt)
        return _verdict_json("supported", 1)

    @property
    def call_count(self) -> int:
        return len(self.prompts)


