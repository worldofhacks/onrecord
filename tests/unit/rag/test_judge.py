def test_importing_judge_does_not_import_the_answer_pipeline():
    # spec(T-026:AC-7)
    # The seam's import must live INSIDE the function body: T-023 is
    # same-wave and unmerged while this ticket is implemented, so a
    # module-level `from onrecord.rag.answer import ...` is a collection
    # error in the wave-9 worktree. Run in a subprocess so another test's
    # imports cannot mask it, and asserted on sys.modules so it stays
    # meaningful AFTER T-023 merges (the laziness is the contract, not the
    # module's absence).
    _module()
    # `sys.stdout.write` rather than the print builtin, which the repo's
    # Tier-1 debug gate greps for in added lines (.tdd-swarm/gates.md).
    code = (
        "import sys; import onrecord.rag.judge as j; "
        "sys.stdout.write('LOADED' if 'onrecord.rag.answer' in sys.modules else 'LAZY'); "
        "sys.stdout.write('HASSEAM' if callable(j._resolve_generator_model) else 'NOSEAM')"
    )
    completed = subprocess.run(
        [sys.executable, "-c", code],
        capture_output=True,
        text=True,
        cwd=str(REPO_ROOT),
        timeout=60,
    )

    assert completed.returncode == 0, (
        f"importing onrecord.rag.judge must succeed with no key, no network and no T-023 "
        f"present; stderr:\n{completed.stderr}"
    )
    assert "LAZY" in completed.stdout, (
        "onrecord.rag.answer must NOT be imported at judge-import time — the generator-model "
        "seam imports it lazily inside the function body"
    )
    assert "HASSEAM" in completed.stdout
