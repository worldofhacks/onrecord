def _require_module_spec(name: str, fail_message: str):
    """Return the module spec for `name`, or fail cleanly via pytest.fail.

    `importlib.util.find_spec` raises ModuleNotFoundError (rather than
    returning None) when a parent package in a dotted name is itself missing,
    so both "not found" cases are normalized into one clean assertion-style
    failure, never an uncaught exception or a pytest collection error.
    """
    try:
        spec = importlib.util.find_spec(name)
    except ModuleNotFoundError:
        spec = None
    if spec is None:
        pytest.fail(fail_message)
    return spec


