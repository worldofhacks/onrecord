def _cell(result: dict, k1: float, b: float) -> dict:
    """The single grid cell at (k1, b); float-tolerant so an implementer may
    generate the b axis by accumulation or by round(i * 0.1, 2)."""
    matches = [
        cell
        for cell in result["grid"]
        if math.isclose(cell["k1"], k1, abs_tol=1e-9) and math.isclose(cell["b"], b, abs_tol=1e-9)
    ]
    assert len(matches) == 1, f"expected exactly one grid cell at (k1={k1}, b={b}), got {matches}"
    return matches[0]


