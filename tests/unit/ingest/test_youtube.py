def test_window_boundary_cue_starting_exactly_at_75s_belongs_to_second_window():
    # spec(T-006:AC-1) -- adversarial: a cue whose start lands exactly on the
    # 75s boundary belongs to the LATER window (window_index = int(start // 75)).
    docs = parse_video_dir(MIXED_BATCH_DIR, LOUDOUN_ENTRY)
    good = {d.id: d for d in _docs_for(docs, GOOD_VIDEO_ID)}
    seg000 = good[f"yt:{GOOD_VIDEO_ID}:seg000"]
    seg001 = good[f"yt:{GOOD_VIDEO_ID}:seg001"]

    boundary_cue_text = "belongs to the next window"
    assert boundary_cue_text in seg001.text, (
        "cue starting at exactly t=75.000s must land in window 1"
    )
    assert boundary_cue_text not in seg000.text


def test_cue_spanning_window_boundary_assigned_by_start_time_not_end_time():
    # spec(T-006:AC-1) -- adversarial: a cue that starts at t=70s and ends at
    # t=82s spans the 75s boundary but is NOT split. Per the documented rule
    # ("a cue belongs to the window containing its start time"), it belongs
    # entirely to window 0, even though two-thirds of its span is in window 1.
    docs = parse_video_dir(MIXED_BATCH_DIR, LOUDOUN_ENTRY)
    good = {d.id: d for d in _docs_for(docs, GOOD_VIDEO_ID)}
    seg000 = good[f"yt:{GOOD_VIDEO_ID}:seg000"]
    seg001 = good[f"yt:{GOOD_VIDEO_ID}:seg001"]

    spanning_cue_text = "seventy five second window boundary"
    assert spanning_cue_text in seg000.text
    assert spanning_cue_text not in seg001.text


