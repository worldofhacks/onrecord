def _callable_or_fail(name: str):
    """Return prices.<name> if present, else a clean pytest.fail (never an
    AttributeError/ModuleNotFoundError traceback). Covers BOTH "the module
    doesn't exist at all yet" (prices is None, per the import guard above)
    and "the module exists but this function isn't defined yet"."""
    obj = getattr(prices, name, None) if prices is not None else None
    if obj is None or not callable(obj):
        pytest.fail(
            f"onrecord.ingest.prices.{name} is not implemented yet "
            f"(onrecord/ingest/prices.py does not exist, or has no callable named {name!r})"
        )
    return obj


def _call_or_fail(fn, *args, **kwargs):
    """Call fn, converting a NotImplementedError stub into a clean pytest.fail —
    the swarm's convention for "a signature-only stub counts as correctly RED"."""
    try:
        return fn(*args, **kwargs)
    except NotImplementedError as exc:
        pytest.fail(f"{getattr(fn, '__name__', fn)} raised NotImplementedError: {exc}")


def _make_transport(
    handlers: dict[str, Callable[[httpx.Request], httpx.Response]],
) -> tuple[httpx.MockTransport, dict[str, int]]:
    """Routes by URL substring (host). Any request that matches no handler
    raises loudly — this is also how a "must never contact FMP" style
    expectation is enforced without a dedicated handler for it. `calls`
    tracks per-key AND total call counts for assertions."""
    calls: dict[str, int] = {"total": 0, **{key: 0 for key in handlers}}

    def handler(request: httpx.Request) -> httpx.Response:
        calls["total"] += 1
        url = str(request.url)
        for key, responder in handlers.items():
            if key in url:
                calls[key] += 1
                return responder(request)
        raise AssertionError(f"unexpected request to an unrouted host: {request.method} {url}")

    return httpx.MockTransport(handler), calls


def _series(pairs: list[tuple[str, float]]) -> list[dict]:
    return [{"date": date, "close": close} for date, close in pairs]


def _write_cache(cache_dir: Path, ticker: str, series: list[dict], fetched_at: datetime) -> None:
    cache_dir.mkdir(parents=True, exist_ok=True)
    payload = {"ticker": ticker, "fetched_at": fetched_at.isoformat(), "series": series}
    (cache_dir / f"{ticker}.json").write_text(json.dumps(payload), encoding="utf-8")


