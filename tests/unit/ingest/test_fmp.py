def test_fetch_transcripts_429_retries_once_then_skips_and_logs(monkeypatch, caplog):
    # spec(T-008:AC-3)
    monkeypatch.setattr(time, "sleep", lambda *_a, **_kw: None)
    fetch_transcripts = _callable_or_fail("fetch_transcripts")

    calls = {"n": 0}

    def handler(request: httpx.Request) -> httpx.Response:
        calls["n"] += 1
        if calls["n"] <= 2:
            return httpx.Response(429, json={"error": "Too Many Requests"})
        raise AssertionError(
            f"expected at most 2 calls (1 initial + 1 backoff retry) for a "
            f"permanently-429 quarter, got a 3rd call: {request.method} {request.url}"
        )

    transport = httpx.MockTransport(handler)

    with caplog.at_level(logging.INFO, logger="onrecord.ingest.fmp"):
        result = _call_or_fail(
            fetch_transcripts,
            "VST",
            [(2025, 2)],
            api_key="fake-test-key",
            transport=transport,
        )

    assert result == [], f"a permanently-429 quarter must be skipped, not returned: {result!r}"
    assert calls["n"] == 2, f"expected exactly 2 HTTP calls (initial + 1 retry), got {calls['n']}"

    matches = [r for r in caplog.records if "429" in r.getMessage()]
    assert len(matches) == 1, (
        f"expected exactly ONE skip-and-log line mentioning 429, got {len(matches)}: "
        f"{[r.getMessage() for r in caplog.records]}"
    )


def test_fetch_transcripts_429_skip_does_not_block_other_quarters(monkeypatch, caplog):
    # spec(T-008:AC-3)
    monkeypatch.setattr(time, "sleep", lambda *_a, **_kw: None)
    fetch_transcripts = _callable_or_fail("fetch_transcripts")
    parse_transcript = _callable_or_fail("parse_transcript")

    ok_payload = _load_fixture("transcript_basic.json")  # 2025 q2, VST
    expected_ok_docs = _call_or_fail(parse_transcript, ok_payload, "VST")

    calls = {"n": 0}

    def handler(request: httpx.Request) -> httpx.Response:
        calls["n"] += 1
        if calls["n"] == 1:
            # First quarter in `quarters` order succeeds.
            return httpx.Response(200, json=[ok_payload])
        if calls["n"] in (2, 3):
            # Second quarter permanently 429s (initial + 1 retry).
            return httpx.Response(429, json={"error": "Too Many Requests"})
        raise AssertionError(f"unexpected 4th HTTP call: {request.method} {request.url}")

    transport = httpx.MockTransport(handler)

    with caplog.at_level(logging.INFO, logger="onrecord.ingest.fmp"):
        result = _call_or_fail(
            fetch_transcripts,
            "VST",
            [(2025, 2), (2025, 1)],
            api_key="fake-test-key",
            transport=transport,
        )

    assert result == expected_ok_docs, (
        "successful quarter's Docs must be returned unchanged; skipped quarter "
        "must contribute nothing"
    )
    assert calls["n"] == 3, f"expected 1 (ok quarter) + 2 (429 quarter) = 3 calls, got {calls['n']}"

    matches = [r for r in caplog.records if "429" in r.getMessage()]
    assert len(matches) == 1, (
        f"expected exactly ONE skip-and-log line for the failing quarter, got {len(matches)}: "
        f"{[r.getMessage() for r in caplog.records]}"
    )


