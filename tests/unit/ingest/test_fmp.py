def test_parse_transcript_basic_three_speakers_six_turns():
    # spec(T-008:AC-1)
    payload = _load_fixture("transcript_basic.json")
    parse_transcript = _callable_or_fail("parse_transcript")

    docs = _call_or_fail(parse_transcript, payload, "VST")

    assert isinstance(docs, list)
    assert len(docs) == 6, (
        f"expected 6 Docs (no consecutive-speaker repeats in fixture), got {len(docs)}"
    )
    assert all(isinstance(d, Doc) for d in docs)

    expected_speakers = [
        "Operator",
        "Jim Burke",
        "Kristopher Moldovan",
        "Operator",
        "Jim Burke",
        "Kristopher Moldovan",
    ]
    assert [d.speaker for d in docs] == expected_speakers

    for i, doc in enumerate(docs, start=1):
        assert doc.id == f"fmp:VST:2025q2:turn{i:03d}", doc.id
        assert doc.source_type == "earnings_call"
        assert doc.venue_type == "coached"
        assert doc.ticker == "VST"
        assert doc.jurisdiction is None
        assert doc.date == "2025-08-07", doc.date
        assert doc.deep_link.startswith(("http://", "https://")), doc.deep_link
        assert doc.text, "Doc.text must not be empty"

    assert docs[0].text.strip().startswith("Good morning, and welcome")
    assert "capital allocation" in docs[5].text


