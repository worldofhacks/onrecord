def _load_fixture(name: str) -> dict:
    path = FIXTURES / name
    assert path.exists(), f"missing fixture: {path}"
    with path.open() as fh:
        return json.load(fh)


def _callable_or_fail(name: str):
    """Return fmp.<name> if present, else a clean pytest.fail (not AttributeError).

    onrecord/ingest/fmp.py currently only has a module docstring — neither
    function exists yet. This converts that into a readable, non-traceback
    failure rather than letting an uncaught AttributeError blow up the test.
    """
    obj = getattr(fmp, name, None)
    if obj is None or not callable(obj):
        pytest.fail(
            f"onrecord.ingest.fmp.{name} is not implemented yet "
            f"(module has no callable named {name!r})"
        )
    return obj


def _call_or_fail(fn, *args, **kwargs):
    """Call fn, converting a NotImplementedError stub into a clean pytest.fail.

    Covers the case where the implementer has landed a signature stub that
    raises NotImplementedError — per the swarm's convention, that counts as
    "correct failure" for a not-yet-implemented adapter, surfaced cleanly
    rather than as a raw traceback.
    """
    try:
        return fn(*args, **kwargs)
    except NotImplementedError as exc:
        pytest.fail(f"{getattr(fn, '__name__', fn)} raised NotImplementedError: {exc}")


def _network_guard_transport() -> httpx.MockTransport:
    """A transport that fails loudly if any HTTP request is ever sent."""

    def handler(request: httpx.Request) -> httpx.Response:  # pragma: no cover - guard
        raise AssertionError(
            f"unexpected live network call in AC-2 test (no api key should mean no "
            f"request is ever sent): {request.method} {request.url}"
        )

    return httpx.MockTransport(handler)


