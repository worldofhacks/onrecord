def _require_module_spec(name: str, fail_message: str):
    """Return the module spec for `name`, or fail cleanly via pytest.fail.

    Mirrors tests/unit/test_scaffold.py's / tests/unit/test_judgments.py's
    established guard idiom: importlib.util.find_spec raises
    ModuleNotFoundError (rather than returning None) when a parent package
    in a dotted name is itself missing, so both "not found" cases are
    normalized into one clean assertion-style failure, never an uncaught
    exception / pytest collection error.
    """
    try:
        spec = importlib.util.find_spec(name)
    except ModuleNotFoundError:
        spec = None
    if spec is None:
        pytest.fail(fail_message)
    return spec


def _api_module():
    _require_module_spec("onrecord.api", "onrecord.api missing")
    import onrecord.api as api_module

    return api_module


def _build_index(tmp_path: Path, docs: list[Doc], name: str = "index") -> Path:
    """Build a real InvertedIndex (real analyzer -- see module docstring's
    "Analyzer" note) and save it to a fresh tmp dir; return that dir."""
    index = InvertedIndex.build(docs)
    index_dir = tmp_path / name
    index.save(index_dir)
    return index_dir


@contextlib.contextmanager
def _client(api_module, monkeypatch, index_dir: Path):
    """Point ONRECORD_INDEX at `index_dir` (present or deliberately absent)
    and open a TestClient context -- this re-runs onrecord.api's ASGI
    startup handler, which must re-read the env var at call time (module
    docstring's AC-5 section) for this per-test swapping to work at all."""
    monkeypatch.setenv("ONRECORD_INDEX", str(index_dir))
    with TestClient(api_module.app) as client:
        yield client


