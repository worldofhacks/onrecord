    hyperscaler = by_sector["hyperscaler_ai"]
    assert hyperscaler["MSFT"]["receipt_count"] == 0
    assert hyperscaler["MSFT"]["last_receipt"] is None

    all_symbols = {sym for row in sectors for sym in [t["symbol"] for t in row["tickers"]]}
    assert "TSLA" not in all_symbols


