    assert [s["sector"] for s in sectors] == ["hyperscaler_ai", "utilities_ipp"]
    for s in sectors:
        assert set(s.keys()) == {"sector", "tickers"}
        for t in s["tickers"]:
            assert set(t.keys()) == {"symbol", "receipt_count", "last_receipt"}

    by_sector = {s["sector"]: {t["symbol"]: t for t in s["tickers"]} for s in sectors}

    utilities = by_sector["utilities_ipp"]
    assert [t["symbol"] for t in sectors[1]["tickers"]] == ["NEE", "VST"]
    assert utilities["VST"]["receipt_count"] == 2
