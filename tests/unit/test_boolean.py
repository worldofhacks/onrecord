# --------------------------------------------------------------------------
# Trivial injected analyzer — stands in for onrecord.analysis.analyzer.analyze
# --------------------------------------------------------------------------


def _analyzer(text: str) -> list[str]:
    """Whitespace-split, lowercased tokenization. Deliberately NOT the real
    analyzer (no NFKC, no punctuation stripping) — just enough to make
    boolean_search/phrase_search's own logic (merges, adjacency, case
    handling via the injected callable) exercisable in isolation."""
    return text.lower().split()


# --------------------------------------------------------------------------
# FakeIndex — in-test stand-in for the frozen InvertedIndex read interface
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class FakePostings:
    """Mirrors the shape of onrecord.index.inverted.Postings (doc_ids, tfs,
    positions) but is a plain frozen dataclass owned by this test module —
    not imported from T-003."""

    doc_ids: list[int]
    tfs: list[int]
    positions: list[list[int]]


class FakeIndex:
    """Minimal in-memory stand-in for `onrecord.index.inverted.InvertedIndex`,
    built directly from a list of `Doc`s — no dependency on T-003's (still
    unimplemented) real index.

    Semantics (the frozen contract this test suite assumes
    `boolean_search`/`phrase_search` are written against):

    - Documents are assigned internal integer ids `0..N-1` in the order
      passed to the constructor. This is the "internal id" that appears in
      `postings(term).doc_ids` and that `get_doc` expects — NOT the external
      `Doc.id` string.
    - `df(term) -> int`: number of distinct docs containing `term`; `0` if
      `term` never occurs (no exception).
    - `postings(term) -> FakePostings`: for an absent term, returns
      `FakePostings(doc_ids=[], tfs=[], positions=[])` (no exception, mirrors
      T-003 AC-5). Otherwise:
        - `.doc_ids`: sorted `list[int]` of internal ids of docs containing
          `term`.
        - `.tfs`: `list[int]` aligned with `.doc_ids`, term frequency of
          `term` in that doc.
        - `.positions`: `list[list[int]]` aligned with `.doc_ids`; each
          inner list is the 0-based token positions (== index into that
          doc's `_analyzer(doc.text)` output, mirroring `analyze()`'s
          "position == list index" contract) at which `term` occurs, in
          ascending order.
    - `doc_count() -> int`: total number of documents in the index.
    - `get_doc(internal_id: int) -> Doc`: fetch the `Doc` for an internal id
      (as yielded by `postings(...).doc_ids`), raising `KeyError` for an
      unknown internal id — mirrors T-003 AC-4's `get_doc` semantics.

    Tokenization for building postings uses the SAME trivial `_analyzer`
    every test injects into `boolean_search`/`phrase_search`, so index-time
    and query-time tokenization always agree, exactly as the real system
    requires (analyzer invariant), without depending on T-002's real
    `analyze()`.
    """

    def __init__(self, docs: list[Doc]) -> None:
        self._docs: dict[int, Doc] = {}
        self._postings: dict[str, dict[int, list[int]]] = {}
        for internal_id, doc in enumerate(docs):
            self._docs[internal_id] = doc
            per_term_positions: dict[str, list[int]] = {}
            for position, token in enumerate(_analyzer(doc.text)):
                per_term_positions.setdefault(token, []).append(position)
            for term, positions in per_term_positions.items():
                self._postings.setdefault(term, {})[internal_id] = positions

    def df(self, term: str) -> int:
        return len(self._postings.get(term, {}))

    def postings(self, term: str) -> FakePostings:
        entries = self._postings.get(term, {})
        doc_ids = sorted(entries)
        return FakePostings(
            doc_ids=doc_ids,
            tfs=[len(entries[d]) for d in doc_ids],
            positions=[entries[d] for d in doc_ids],
        )

    def doc_count(self) -> int:
        return len(self._docs)

    def get_doc(self, internal_id: int) -> Doc:
        return self._docs[internal_id]


def _ids(results: list[SearchResult]) -> set[str]:
    return {r.doc_id for r in results}


