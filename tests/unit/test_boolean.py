def test_boolean_search_and_returns_intersection_only(boolean_corpus):
    # spec(T-004:AC-1)
    results = boolean_search(boolean_corpus, "loudoun substation", "AND", analyzer=_analyzer)
    assert _ids(results) == {"docA"}
    assert len(results) == 1


def test_boolean_search_and_disjoint_postings_returns_empty(boolean_corpus):
    """Adversarial: 'denied' (df=1, only docB) and 'park' (df=1, only docC)
    each individually exist in the corpus, but no single doc contains both —
    AND's k-way intersection over disjoint posting lists must yield [], not
    raise, and not accidentally degrade into a union."""
    # spec(T-004:AC-1)
    results = boolean_search(boolean_corpus, "denied park", "AND", analyzer=_analyzer)
    assert results == []


def test_boolean_search_results_are_searchresults_with_external_doc_ids(boolean_corpus):
    """Guards against conflating FakeIndex's internal integer ids (0, 1, 2, ...)
    with the external Doc.id string that SearchResult.doc_id must carry."""
    # spec(T-004:AC-1)
    results = boolean_search(boolean_corpus, "loudoun", "OR", analyzer=_analyzer)
    assert results, "expected at least one match for 'loudoun'"
    for r in results:
        assert isinstance(r, SearchResult)
        assert isinstance(r.doc_id, str)
        assert r.doc_id in {"docA", "docB", "docC"}
        assert isinstance(r.score, float)
        assert isinstance(r.snippet, str)


