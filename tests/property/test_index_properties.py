# Property: round-trip retrievability
# ---------------------------------------------------------------------------


@given(docs=_doc_lists())
@settings(max_examples=40, deadline=None)
def test_property_every_doc_retrievable_via_each_distinct_term(docs):
    # spec(T-003:AC-1)
    # spec(T-003:AC-2)
    idx = InvertedIndex.build(docs, analyzer=TRIVIAL_ANALYZER)

    # Scheme-agnostic: every doc comes back byte-for-byte via its external id.
    for doc in docs:
        assert idx.get_doc(doc.id) == doc

    # Per pinned build-order-id assumption: doc i's own terms must include
    # doc i's internal id in their postings, with tf/positions matching the
    # injected analyzer's output exactly.
    for i, doc in enumerate(docs):
        tokens = TRIVIAL_ANALYZER(doc.text)
        for term in set(tokens):
            postings = idx.postings(term)
            doc_ids = list(postings.doc_ids)
            assert i in doc_ids, f"doc {doc.id!r} (internal id {i}) missing from postings({term!r})"
            j = doc_ids.index(i)
            assert postings.tfs[j] == tokens.count(term)
            expected_positions = [pos for pos, t in enumerate(tokens) if t == term]
            assert list(postings.positions[j]) == expected_positions


# ---------------------------------------------------------------------------
# Property: delete purges the doc everywhere, never returned again
# ---------------------------------------------------------------------------


@given(pair=_doc_lists_with_victim())
@settings(max_examples=40, deadline=None)
def test_property_delete_purges_everywhere(pair):
    # spec(T-003:AC-4)
    docs, victim_index = pair
    idx = InvertedIndex.build(docs, analyzer=TRIVIAL_ANALYZER)

    victim = docs[victim_index]
    survivors_tokens = [
        set(TRIVIAL_ANALYZER(d.text)) for j, d in enumerate(docs) if j != victim_index
    ]
    victim_terms = set(TRIVIAL_ANALYZER(victim.text))

    idx.delete(victim.id)

    assert idx.doc_count() == len(docs) - 1
    try:
        idx.get_doc(victim.id)
    except KeyError:
        pass
    else:
        raise AssertionError(f"get_doc({victim.id!r}) should raise KeyError after delete")

    for term in victim_terms:
        expected_df = sum(1 for toks in survivors_tokens if term in toks)
        assert idx.df(term) == expected_df, f"df({term!r}) wrong after deleting sole/one holder"

        postings = idx.postings(term)
        doc_ids = list(postings.doc_ids)
        assert len(doc_ids) == expected_df
        assert len(list(postings.tfs)) == expected_df
        assert len(list(postings.positions)) == expected_df
        if expected_df == 0:
            # Term was unique to the deleted doc: purged everywhere, no exception.
            assert doc_ids == []
            assert list(postings.tfs) == []
            assert list(postings.positions) == []
        else:
            # Victim's own (build-order) internal id must be gone from postings.
            assert victim_index not in doc_ids


# ---------------------------------------------------------------------------
# Property: df correctness (+ sortedness of postings)
# ---------------------------------------------------------------------------


@given(docs=_doc_lists())
@settings(max_examples=40, deadline=None)
def test_property_df_equals_number_of_docs_containing_term(docs):
    # spec(T-003:AC-1)
    # spec(T-003:AC-5)
    idx = InvertedIndex.build(docs, analyzer=TRIVIAL_ANALYZER)

    per_doc_terms = [set(TRIVIAL_ANALYZER(d.text)) for d in docs]
    all_terms = set().union(*per_doc_terms) if per_doc_terms else set()

    for term in all_terms | {ABSENT_TERM}:
        expected_df = sum(1 for terms in per_doc_terms if term in terms)
        assert idx.df(term) == expected_df

        postings = idx.postings(term)
        doc_ids = list(postings.doc_ids)
        assert len(doc_ids) == expected_df
        assert len(list(postings.tfs)) == expected_df
        assert len(list(postings.positions)) == expected_df

        # Postings must always be sorted ascending with no duplicate doc ids,
        # even for df == 0 (empty, trivially sorted) — no exception either way.
        assert doc_ids == sorted(doc_ids)
        assert len(set(doc_ids)) == len(doc_ids)

    # The never-present term specifically: df==0, empty postings, no exception.
    assert idx.df(ABSENT_TERM) == 0
    absent_postings = idx.postings(ABSENT_TERM)
    assert list(absent_postings.doc_ids) == []
    assert list(absent_postings.tfs) == []
    assert list(absent_postings.positions) == []
