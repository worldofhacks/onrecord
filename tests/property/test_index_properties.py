from __future__ import annotations

from hypothesis import given, settings
from hypothesis import strategies as st

from onrecord.index.inverted import InvertedIndex
from onrecord.types import Doc

# Small closed vocabulary keeps overlap between docs frequent (so df > 1
# cases actually get exercised) while staying trivially tokenizable by the
# injected analyzer (whitespace-split, lowercased).
WORDS = [
    "substation",
    "transformer",
    "county",
    "grid",
    "filing",
    "hearing",
    "megawatt",
    "capacity",
    "line",
    "request",
]

ABSENT_TERM = "zz-never-in-vocabulary-zz"


def TRIVIAL_ANALYZER(text: str) -> list[str]:
    return text.lower().split()


def _doc(doc_id: str, text: str, n: int) -> Doc:
    return Doc(
        id=doc_id,
        text=text,
        source_type="filing",
        venue_type="written",
        date="2024-01-01",
        deep_link=f"https://example.test/{n}",
    )


@st.composite
def _doc_lists(draw, min_size: int = 1, max_size: int = 6):
    n = draw(st.integers(min_value=min_size, max_value=max_size))
    ids = draw(
        st.lists(
            st.from_regex(r"[a-z][a-z0-9_]{2,9}", fullmatch=True),
            min_size=n,
            max_size=n,
            unique=True,
        )
    )
    docs = []
    for i, doc_id in enumerate(ids):
        words = draw(st.lists(st.sampled_from(WORDS), min_size=1, max_size=6))
        docs.append(_doc(doc_id, " ".join(words), i))
    return docs


@st.composite
def _doc_lists_with_victim(draw, min_size: int = 2, max_size: int = 6):
    docs = draw(_doc_lists(min_size=min_size, max_size=max_size))
    victim_index = draw(st.integers(min_value=0, max_value=len(docs) - 1))
    return docs, victim_index


