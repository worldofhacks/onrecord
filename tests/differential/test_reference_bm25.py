@pytest.mark.parametrize("query", FIXTURE_QUERIES)
def test_ac2_score_agrees_via_documented_constant_transform(query, fixture_index):
    # spec(T-012:AC-2)
    diff_mod = _import_differential_module()

    terms = analyze(query)
    dfs = {fixture_index.df(t) for t in terms}
    assert len(dfs) == 1, f"fixture query {query!r} must be single-df by construction"
    (df,) = dfs
    N = fixture_index.doc_count()
    idf_ours = math.log(1 + (N - df + 0.5) / (df + 0.5))
    idf_theirs_raw = math.log((N - df + 0.5) / (df + 0.5))
    assert idf_theirs_raw > 0, "fixture df must stay below N/2 (module docstring)"
    expected_c = idf_ours / idf_theirs_raw

    report = diff_mod.run_differential(FIXTURE_DOCS, [query], k1=1.5, b=0.75, k=10)
    qd = report.query_diffs[0]

    assert qd.score_transform is not None, (
        f"query {query!r} is same-df by construction -- score_transform must be computed"
    )
    assert qd.score_transform == pytest.approx(expected_c, rel=1e-9)
    assert qd.max_rel_score_diff is not None
    assert qd.max_rel_score_diff < 1e-6, (
        f"query {query!r}: max relative score deviation {qd.max_rel_score_diff} after "
        f"applying the documented c-transform exceeds 1e-6 -- systematic deviation"
    )


