# --------------------------------------------------------------------------
# AC-3 -- property (assignment invariant 3, per docs/presearch-transcript.md
# section D: "a doc gaining a query term cannot rank below an identical doc
# lacking it"), tested against OUR implementation (InvertedIndex +
# ranked_search), NOT the reference library.
#
# Formalized as: an "otherwise-identical" doc means SAME total token count
# -- `extra` filler tokens are swapped out for `extra` more occurrences of
# the query term (never appended, which would grow doc_len and could
# legitimately violate the invariant for MULTI-term queries once a
# companion term's length-normalization penalty outweighs the target
# term's own tf-saturation gain -- discovered and verified with a
# throwaway reference implementation before freezing; see the Test Agent's
# handoff report. T-011's own tf-monotonicity property
# (tests/unit/test_bm25.py) similarly holds doc_len/avg_doc_len fixed, for
# the same underlying reason). Verified over 1000+ hypothesis examples
# against the real InvertedIndex + ranked_search stack (both single- and
# two-term OR queries, 0-4 extra corpus docs) before freezing.
# --------------------------------------------------------------------------


def TRIVIAL_ANALYZER(text: str) -> list[str]:
    return text.lower().split()


def _ac3_doc(doc_id: str, tokens: list[str], n: int) -> Doc:
    return Doc(
        id=doc_id,
        text=" ".join(tokens),
        source_type="filing",
        venue_type="written",
        date="2025-01-01",
        deep_link=f"https://example.test/{n}",
    )


_AC3_FILLERS = ["alpha", "bravo", "charlie", "delta", "echo", "foxtrot", "golf", "hotel"]
_AC3_TARGETS = ["zeta", "yankee", "xray"]


@st.composite
def _ac3_params(draw):
    target = draw(st.sampled_from(_AC3_TARGETS))
    companion = draw(st.one_of(st.none(), st.sampled_from(_AC3_FILLERS)))
    non_query_fillers = [f for f in _AC3_FILLERS if f != companion]
    extra = draw(st.integers(min_value=1, max_value=5))
    total_len = draw(st.integers(min_value=extra + 1, max_value=extra + 15))
    base_tf = draw(st.integers(min_value=0, max_value=total_len - extra))
    filler_slots = total_len - base_tf  # guaranteed >= extra -- never falls
    # back to doc-length growth (see docstring above for why that matters).
    filler_pool = draw(
        st.lists(st.sampled_from(non_query_fillers), min_size=filler_slots, max_size=filler_slots)
    )
    n_other_docs = draw(st.integers(min_value=0, max_value=4))
    other_docs_tokens = draw(
        st.lists(
            st.lists(st.sampled_from([*_AC3_FILLERS, target]), min_size=1, max_size=10),
            min_size=n_other_docs,
            max_size=n_other_docs,
        )
    )
    return target, base_tf, extra, filler_pool, other_docs_tokens, companion


@given(params=_ac3_params())
@settings(max_examples=200, deadline=None)
def test_property_doc_gaining_a_query_term_occurrence_never_ranks_below_doc_lacking_it(params):
    # spec(T-012:AC-3)
    target, base_tf, extra, filler_pool, other_docs_tokens, companion = params

    less_tokens = filler_pool + [target] * base_tf
    more_tokens = filler_pool[:-extra] + [target] * (base_tf + extra)
    assert len(less_tokens) == len(more_tokens), "otherwise-identical: doc_len must be held fixed"

    docs = [_ac3_doc("doc_less", less_tokens, 0), _ac3_doc("doc_more", more_tokens, 1)]
    for i, tokens in enumerate(other_docs_tokens):
        docs.append(_ac3_doc(f"doc_other_{i}", tokens, 2 + i))

    idx = InvertedIndex.build(docs, analyzer=TRIVIAL_ANALYZER)
    query = target if companion is None else f"{target} {companion}"

    results = ranked_search(idx, query, k=len(docs), analyzer=TRIVIAL_ANALYZER)
    scores = {r.doc_id: r.score for r in results}
    less_score = scores.get("doc_less", 0.0)
    more_score = scores.get("doc_more", 0.0)

    assert more_score >= less_score - 1e-9, (
        f"target={target} base_tf={base_tf} extra={extra} companion={companion}: "
        f"doc_more (tf={base_tf + extra}) scored {more_score} < "
        f"doc_less (tf={base_tf}) scored {less_score}"
    )


