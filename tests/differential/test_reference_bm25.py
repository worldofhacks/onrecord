# AC-4 -- `python -m onrecord.eval.differential` exit-code contract: 0 on
# agreement (main fixture), 1 with a per-query diff table on divergence
# (divergence fixture, module docstring).
# --------------------------------------------------------------------------

_CLI_TIMEOUT = 60


def _run_differential_cli(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, "-m", "onrecord.eval.differential", *args],
        capture_output=True,
        text=True,
        timeout=_CLI_TIMEOUT,
    )


def test_ac4_cli_exits_zero_on_the_agreeing_main_fixture():
    # spec(T-012:AC-4)
    _require_module_spec("onrecord.eval.differential", "onrecord.eval.differential missing")
    proc = _run_differential_cli("--corpus", str(CORPUS_PATH), "--queries", str(QUERIES_PATH))
    assert proc.returncode == 0, f"stdout:\n{proc.stdout}\nstderr:\n{proc.stderr}"


def test_ac4_cli_exits_nonzero_with_per_query_diff_table_on_the_divergence_fixture():
    # spec(T-012:AC-4)
    _require_module_spec("onrecord.eval.differential", "onrecord.eval.differential missing")

    # Independent sanity check: this fixture must genuinely diverge,
    # verified straight off the real InvertedIndex + a fresh BM25Okapi --
    # never assume the CLI's own report is correct without cross-checking.
    div_docs = _load_corpus(DIVERGENCE_CORPUS_PATH)
    div_queries = _load_queries(DIVERGENCE_QUERIES_PATH)
    assert len(div_queries) == 1
    div_index = InvertedIndex.build(div_docs)
    _, _, _, expected_our_order, expected_ref_order = _independent_expected_diff(
        div_docs, div_index, div_queries[0]
    )
    assert expected_our_order != expected_ref_order, (
        "sanity check failed: the divergence fixture no longer actually diverges "
        "independently of the CLI -- fixture or analyzer behavior changed"
    )

    proc = _run_differential_cli(
        "--corpus", str(DIVERGENCE_CORPUS_PATH), "--queries", str(DIVERGENCE_QUERIES_PATH)
    )
    assert proc.returncode == 1, f"stdout:\n{proc.stdout}\nstderr:\n{proc.stderr}"
    assert div_queries[0] in proc.stdout, "diff table must identify which query diverged"
    for doc_id in expected_our_order:
        assert doc_id in proc.stdout, f"diff table must show doc id {doc_id!r} from the ranking"
    assert len(proc.stdout.strip().splitlines()) >= 2, (
        "must be a genuine per-query table, not one line"
    )


def test_ac4_cli_missing_required_args_is_a_usage_error_not_a_crash_on_none():
    # spec(T-012:AC-4) -- --corpus/--queries are required (module docstring:
    # onrecord/ production code never bakes a default path into tests/), so
    # omitting them must be argparse's own usage-error path (exit code 2),
    # not an unguarded crash trying to open path `None`.
    _require_module_spec("onrecord.eval.differential", "onrecord.eval.differential missing")
    proc = _run_differential_cli()
    assert proc.returncode == 2, f"stdout:\n{proc.stdout}\nstderr:\n{proc.stderr}"


def test_ac4_main_function_returns_int_directly_matching_cli_exit_code(fixture_index):
    # spec(T-012:AC-4) -- `main(argv)` itself (not just the subprocess/CLI
    # wrapper) returns the same 0/1 contract, called with an explicit argv
    # list (never relying on sys.argv), matching onrecord.eval.judgments's
    # `main(argv=None)` convention.
    diff_mod = _import_differential_module()
    del fixture_index  # not used directly -- CORPUS_PATH/QUERIES_PATH are module-level

    rc_ok = diff_mod.main(["--corpus", str(CORPUS_PATH), "--queries", str(QUERIES_PATH)])
    assert rc_ok == 0

    rc_diverge = diff_mod.main(
        ["--corpus", str(DIVERGENCE_CORPUS_PATH), "--queries", str(DIVERGENCE_QUERIES_PATH)]
    )
    assert rc_diverge == 1
