def _load_corpus(path: Path) -> list[Doc]:
    docs = []
    with path.open("r", encoding="utf-8") as fh:
        for line in fh:
            stripped = line.strip()
            if stripped:
                docs.append(Doc(**json.loads(stripped)))
    return docs


def _load_queries(path: Path) -> list[str]:
    with path.open("r", encoding="utf-8") as fh:
        return [line.strip() for line in fh if line.strip()]


