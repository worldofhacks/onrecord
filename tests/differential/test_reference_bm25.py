# --------------------------------------------------------------------------
# Independent reference computations -- never call run_differential to
# compute what run_differential is being checked against (would make the
# test tautological). Mirrors tests/unit/test_bm25.py's `_ref_doc_score`
# pattern: hand-computed, straight off the real InvertedIndex's own stats
# plus a freshly-built rank_bm25.BM25Okapi.
# --------------------------------------------------------------------------


def _independent_our_scores(
    index: InvertedIndex, terms: list[str], k1: float = 1.5, b: float = 0.75
) -> dict[str, float]:
    N = index.doc_count()
    avg_len = index.avg_doc_length()
    candidate_ids: set[int] = set()
    for t in terms:
        candidate_ids.update(index.postings(t).doc_ids)
    scores: dict[str, float] = {}
    for iid in candidate_ids:
        doc_len = index.doc_length(iid)
        total = 0.0
        for t in terms:
            df = index.df(t)
            postings = index.postings(t)
            doc_ids = list(postings.doc_ids)
            tf = list(postings.tfs)[doc_ids.index(iid)] if iid in doc_ids else 0
            total += bm25_score(tf, df, N, doc_len, avg_len, k1=k1, b=b)
        scores[index.get_doc(iid).id] = total
    return scores


def _independent_reference_scores(
    docs: list[Doc], terms: list[str], k1: float = 1.5, b: float = 0.75
) -> dict[str, float]:
    token_lists = [analyze(d.text) for d in docs]
    reference = BM25Okapi(token_lists, k1=k1, b=b)
    raw_scores = reference.get_scores(terms)
    return {docs[i].id: float(raw_scores[i]) for i in range(len(docs))}


def _independent_expected_diff(docs, index, query, k1=1.5, b=0.75, k=10):
    """Full independent (query, expected top-k order per system) pair --
    used by both AC-1 and AC-4 to cross-check run_differential's output."""
    terms = analyze(query)
    our_scores = _independent_our_scores(index, terms, k1, b)
    ref_scores_all = _independent_reference_scores(docs, terms, k1, b)
    candidate_ids = set(our_scores)
    ref_scores = {d: ref_scores_all[d] for d in candidate_ids}
    our_order = sorted(candidate_ids, key=lambda d: (-our_scores[d], d))[:k]
    ref_order = sorted(candidate_ids, key=lambda d: (-ref_scores[d], d))[:k]
    return terms, our_scores, ref_scores, our_order, ref_order


